//go:build stories && !windows

package stories

// O_adopt_oldformat_test.go — devco:D-719 on the owner-shaped machine
// (story O): the owner's client repos were still on the lore 0.1.17
// format with open rows on the live ref. `lore row move` refused there
// (E_FORMAT_OLD), so the live rows could not leave for the store, and
// the repo's old .lore/LORE.md (render writes none in a linked repo)
// blocked every commit that touched it. Now `lore store adopt --move
// --commit` moves such a repo in one command: it reads the old format
// (never migrates it), takes the live rows off the ref, removes the row
// files, _meta.json and the stale LORE.md (and says so), links the repo
// and the commit goes through the repo's hooks.

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestStoryOAdoptMoveOldFormat(t *testing.T) {
	s := New(t, "O")
	team := s.Remote("github.com/" + oOwner + "/lore-team")
	platform := s.Seed(s.Remote("github.com/"+oOwner+"/platform"), func(dir string) { PlainRepo(t, dir) })
	ledger := s.Seed(s.Remote("github.com/"+oOwner+"/ledger-old"), func(dir string) { PlainRepo(t, dir) })

	ada := s.OwnerShaped(OwnerShape{Personal: oAdminPersonal, Org: oAdminOrg, OrgFolder: oOrg, Alias: oAlias, OrgOwners: []string{oOwner}})
	pc := ada.CloneTo(platform, ada.OrgDir("platform"))
	oSetupFlow(t, ada, pc.Dir, oSetup, "admin", oAdminOrg, oAlias,
		map[string]any{"org": oOrg, "store_url": team.SSHURL()}, []string{"~/code/" + oOrg + "/**"})
	lc := ada.CloneTo(ledger, ada.OrgDir("ledger-old"))
	const folder = "ledger_old"
	place := oOrg + "/" + folder
	var task string
	var prj V017Project

	s.Step("D-719/a-0.1.17-format-repo-with-an-open-live-row", func() {
		ada.Lore(lc.Dir, "init", "--non-interactive", "--name=ledger-old").OK(t)
		r := ada.Lore(lc.Dir, "task", "add", "reconcile the old ledger", "--to", "repo", "--json").OK(t)
		i := strings.Index(r.Stdout, `"id": "tsk_`)
		if i < 0 {
			t.Fatalf("task add printed no id:\n%s", r.Stdout)
		}
		task = r.Stdout[i+len(`"id": "`) : i+len(`"id": "`)+36]
		// the repo's committed rows are then a teammate's lore 0.1.17
		// ones (format 1, LORE.md committed), the live row stays
		if err := os.RemoveAll(filepath.Join(lc.Dir, ".lore", "data")); err != nil {
			t.Fatal(err)
		}
		prj = V017Repo(t, lc.Dir, "ledger-old", SmallShape)
		// what 0.1.17's render put in LORE.md: the repo's rules, in full
		rule, _ := lc.ReadFile(".lore/data/rules/" + prj.Rows["rules"][0] + ".json")
		lc.WriteFile(".lore/LORE.md", "<!-- This file is generated by lore render. Do not edit by hand. -->\n\n# ledger-old\n\n## Rules\n\n"+rule+"\n")
		lc.Git("add", "-A", "-f", ".lore/data", ".lore/LORE.md", ".gitignore")
		lc.Git("-c", "core.hooksPath=/dev/null", "commit", "-q", "-m", "lore 0.1.17 notes")
		lc.Git("push", "-q", "origin", "HEAD:main")
		if !strings.Contains(lc.Git("ls-tree", "-r", "--name-only", "refs/lore/live"), task) {
			t.Fatalf("the open task is not on the live ref: the step would prove nothing")
		}
		if lc.Git("ls-files", ".lore/LORE.md") == "" {
			t.Fatalf("the old LORE.md is not committed: the step would prove nothing")
		}
		if r := ada.Lore(lc.Dir, "row", "move", "--id", task, "--to", place); r.Code == 0 {
			t.Logf("row move in the 0.1.17-format repo went through:\n%s", r.Stdout)
		}
		ada.Lore(pc.Dir, "store", "folder", "add", oOrg, folder).OK(t)
	})

	s.Step("D-719/one-command-moves-the-old-format-repo", func() {
		r := ada.Lore(lc.Dir, "store", "adopt", "--target", place, "--move", "--commit", "--yes")
		t.Logf("adopt --move in a 0.1.17-format repo:\n%s\n%s", r.Stdout, r.Stderr)
		r.OK(t).Says(t, "off the repo's live ref", "and committed it (", "link: ",
			"removed .lore/LORE.md (lore renders no LORE.md", "removed .lore/data/_meta.json (the repo's lore 0.1.17 format marker",
			"removed .lore/data/projects/"+prj.ID+".json").
			Never(t, "E_FORMAT_OLD", "lore migrate run", "left in the repo: projects")
		if got := lc.Git("log", "-1", "--format=%s"); got != "lore: move the notes to "+place {
			t.Fatalf("the repo's last commit is %q", got)
		}
		if out := lc.Git("ls-files", ".lore"); out != "" {
			t.Errorf("the repo still tracks lore files after the move:\n%s", out)
		}
		if strings.Contains(lc.Git("ls-tree", "-r", "--name-only", "refs/lore/live"), task) {
			t.Errorf("the moved task is still on the repo's live ref")
		}
		ada.Lore(lc.Dir, "show", "--id", task).OK(t).Never(t, "two live rows", "E_AMBIGUOUS_ID")
		ada.Lore(lc.Dir, "show", "--id", prj.Rows["rules"][0]).OK(t)
		// a later commit touching the repo goes through the hooks
		lc.WriteFile("main.go", "package main\n\n// after the move\n")
		lc.CommitAll("after the move")
		lc.Git("push", "-q", "origin", "HEAD:main")
	})
}
