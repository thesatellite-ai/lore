// Always are the rows every task may be shown (rules with activation
// always): they apply everywhere, so they are never noise.
func Always() []string {
	var out []string
	for _, r := range Rows() {
		if r.Act == ActAlways {
			out = append(out, r.Key)
		}
	}
	return out
}

// Validate checks the data set: unique keys, every task's rows exist,
// required rows are must-rules or critical hotfixes, 30 tasks.
func Validate() error {
	rows := map[string]Row{}
	for _, r := range Rows() {
		if _, dup := rows[r.Key]; dup {
			return fmt.Errorf("row %s twice", r.Key)
		}
		rows[r.Key] = r
	}
	ts := Tasks()
	if len(ts) != 30 {
		return fmt.Errorf("want 30 tasks, have %d", len(ts))
	}
	ids := map[string]bool{}
	for _, t := range ts {
		if ids[t.ID] {
			return fmt.Errorf("task %s twice", t.ID)
		}
		ids[t.ID] = true
		for _, k := range t.Applies() {
			if _, ok := rows[k]; !ok {
				return fmt.Errorf("task %s names row %s, which does not exist", t.ID, k)
			}
		}
		for _, k := range t.Required {
			r := rows[k]
			if !(r.Kind == KindRule && r.Severity == "must" || r.Kind == KindHotfix && r.Severity == "critical") {
				return fmt.Errorf("task %s requires %s, which is neither a must-rule nor a critical hotfix", t.ID, k)
			}
		}
	}
	return nil
}
