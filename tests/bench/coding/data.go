// Package coding is the coding-agent context gate (devco D-815): a
// synthetic repo whose lore store holds rules, hotfixes, decisions,
// patterns and memories, and 30 coding tasks (a file path and the task's
// words), each with the rows that must reach the agent before it edits.
//
//	Rows ──lore rule/hotfix/decision/pattern/memory add──▶ repo store
//	Task{File, Text} ──▶ lore context --for-file File   ┐ arm "context"
//	                 ──▶ lore context --for-prompt Text ┘ (what the hooks send)
//	                 ──▶ lore ask --query "Text in File"  arm "ask"
//	ids printed ──Grade──▶ recall of Required (must-rules, critical
//	                       hotfixes) and precision over Applies
//
// Why a separate gate from the recall bench (tests/bench/recall): that one
// asks a personal store about people, projects and days; this one asks
// what an agent about to change a file must know. Lore's core job is the
// second, and a miss there is a broken build or a repeated outage, not a
// wrong answer.
//
// Traps (trap.go) are the concrete wrong edits each critical hotfix
// forbids, with a checker over an agent's diff, for the blind-agent half
// (an agent with lore avoids the trap, an agent without it falls in).
package coding

import (
	"fmt"
	"slices"
)

// Kind is the lore table a row is written to.
type Kind string

// The kinds the gate writes (each is a `lore <kind> add`).
const (
	KindRule     Kind = "rule"
	KindHotfix   Kind = "hotfix"
	KindDecision Kind = "decision"
	KindPattern  Kind = "pattern"
	KindMemory   Kind = "memory"
)

// Activation is a rule's --activation.
type Activation string

// Rule activations (lore rule add --activation).
const (
	ActAlways   Activation = "always"
	ActGlob     Activation = "glob"
	ActSemantic Activation = "semantic"
)

// Row is one row of the store, written by lore.
type Row struct {
	Key      string // the gate's own name for the row (Task.Required names it)
	Kind     Kind
	Title    string
	Body     string
	Severity string     // rules: must | should | may; hotfixes: low … critical
	Act      Activation // rules only
	Globs    []string   // rules with ActGlob
	Applies  string     // rules with ActSemantic: --applies-to
	Scope    string     // "" (the repo) or dir:<folder>
}

// Task is one coding task: the file the agent edits and what it was asked.
type Task struct {
	ID   string
	File string
	Text string
	// Required are the rows the agent must be shown (must-rules and
	// critical hotfixes that apply): recall over them has to be 100%.
	Required []string
	// Also are rows that apply too (should-rules, decisions, scoped notes,
	// lower hotfixes): showing them is not noise.
	Also []string
}

// Applies is every row that applies to t (Required and Also).
func (t Task) Applies() []string { return append(slices.Clone(t.Required), t.Also...) }

// AskQuery is how an agent puts the task to `lore ask`: its words and the
// file it is about to edit.
func (t Task) AskQuery() string { return t.Text + " in " + t.File }

