// campaign_render_init_test.go — `lore init` in every kind of folder a
// person runs it in (CLI_REFERENCE init, TOOL NEUTRAL, G-MONO-1):
//   - a git repo with no tool file, and with each tool's own file already
//     there (CLAUDE.md, AGENTS.md, GEMINI.md, the Copilot file, Cursor's
//     lore.mdc), plus a legacy .cursorrules lore does not own (it picks cursor): the
//     detected tools are wired, hand text stays below the pointer, a file
//     lore does not own is never touched, and the choice is saved as the
//     context.targets policy;
//   - a folder that is no git repo, a read-only checkout, a repo nested in
//     another, a sub-folder project of an initialised repo;
//   - init twice (a clear refusal that writes nothing), init <path>;
//   - odd project names (spaces, unicode, RTL, 10k chars, upper case).

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	th "github.com/thesatellite-ai/lore/tests/teame2e/teamharness"
)

// campPolicyRow is one entry of `lore policy show --json`.
type campPolicyRow struct {
	Key    string `json:"key"`
	Value  string `json:"value"`
	Source string `json:"source"`
	Level  string `json:"level"`
	Row    string `json:"row"`
	Store  string `json:"store"`
	Doc    string `json:"doc"`
}

// campPolicyShow is `lore policy show [key] --json`.
type campPolicyShow struct {
	Count int             `json:"count"`
	Data  []campPolicyRow `json:"data"`
}

// campTargets is the saved context.targets value of c ("" when unset).
func campTargets(t *testing.T, c *th.Clone) string {
	t.Helper()
	got := campJSON[campPolicyShow](t, c.Lore("policy", "show", "context.targets", "--json"))
	if got.Count != 1 || len(got.Data) != 1 {
		t.Fatalf("policy show context.targets: one row, got %+v", got)
	}
	return got.Data[0].Value
}

func TestCampaignRender_InitToolFileMatrix(t *testing.T) {
	const hand = "# my notes\nkeep this line\n"
	cases := []struct {
		name string
		// files are written before init (path → body).
		files map[string]string
		// targets is the saved context.targets value.
		targets string
		// wired are the pointer files init stitches, with their pointer.
		wired map[string]string
		// absent are files init must not create.
		absent []string
	}{
		{name: "no tool file", targets: "codex",
			wired: map[string]string{"AGENTS.md": renderPtrRead}, absent: []string{"CLAUDE.md", "GEMINI.md", ".cursor/rules/lore.mdc"}},
		{name: "CLAUDE.md", files: map[string]string{"CLAUDE.md": hand}, targets: "claude_code",
			wired: map[string]string{"CLAUDE.md": renderPtrAt}, absent: []string{"AGENTS.md"}},
		{name: "AGENTS.md", files: map[string]string{"AGENTS.md": hand}, targets: "codex",
			wired: map[string]string{"AGENTS.md": renderPtrRead}, absent: []string{"CLAUDE.md"}},
		{name: "GEMINI.md", files: map[string]string{"GEMINI.md": hand}, targets: "gemini_cli",
			wired: map[string]string{"GEMINI.md": renderPtrAt}, absent: []string{"AGENTS.md", "CLAUDE.md"}},
		{name: "copilot", files: map[string]string{".github/copilot-instructions.md": hand}, targets: "copilot",
			wired: map[string]string{".github/copilot-instructions.md": renderPtrRead}, absent: []string{"AGENTS.md"}},
		// A hand-made lore.mdc without frontmatter gets the read block on
		// top (render_targets_test pins the same for render).
		{name: "cursor mdc", files: map[string]string{".cursor/rules/lore.mdc": hand}, targets: "cursor",
			wired: map[string]string{".cursor/rules/lore.mdc": renderPtrRead}, absent: []string{"AGENTS.md"}},
		// A legacy .cursorrules shows the repo uses Cursor: the cursor
		// profile is picked and its own lore.mdc wired, while .cursorrules
		// (not a file lore owns) stays byte for byte.
		{name: "legacy .cursorrules", files: map[string]string{".cursorrules": hand}, targets: "cursor",
			wired: map[string]string{".cursor/rules/lore.mdc": "---\ndescription: lore project knowledge (generated by lore render)\nalwaysApply: true\n---\n" + renderPtrRead}, absent: []string{"AGENTS.md", "CLAUDE.md"}},
		// So does any Cursor rule file of the person's own.
		{name: "a cursor rule file", files: map[string]string{".cursor/rules/style.mdc": hand}, targets: "cursor",
			wired: map[string]string{".cursor/rules/lore.mdc": "---\ndescription: lore project knowledge (generated by lore render)\nalwaysApply: true\n---\n" + renderPtrRead}, absent: []string{"AGENTS.md", "CLAUDE.md"}},
		{name: "CLAUDE.md and AGENTS.md", files: map[string]string{"CLAUDE.md": hand, "AGENTS.md": hand}, targets: "claude_code, codex",
			wired: map[string]string{"CLAUDE.md": renderPtrAt, "AGENTS.md": renderPtrRead}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			c := campFresh(t)
			for f, b := range tc.files {
				c.WriteFile(f, b)
			}
			r := c.MustLore("init", "--name=tool")
			r.Says(t, "lore initialized", "project_id: prj_", "repo_id:    rep_", "· context targets: ", "next: lore render")
			if got := campTargets(t, c); got != tc.targets {
				t.Errorf("context.targets = %q, want %q", got, tc.targets)
			}
			for f, ptr := range tc.wired {
				got := renderRead(t, c, f)
				if !strings.HasPrefix(got, ptr) {
					t.Errorf("%s starts with lore's pointer %q:\n%s", f, ptr, got)
				}
				if hb, had := tc.files[f]; had && !strings.HasSuffix(got, hb) {
					t.Errorf("%s keeps the person's text below the pointer:\n%s", f, got)
				}
				r.Says(t, f+" (pointer → ") // the path is relative to the pointer file
			}
			for _, f := range tc.absent {
				if _, ok := c.ReadFile(f); ok {
					t.Errorf("init creates no %s here", f)
				}
			}
			if b, ok := tc.files[".cursorrules"]; ok {
				if got := renderRead(t, c, ".cursorrules"); got != b {
					t.Errorf(".cursorrules is never touched: %q", got)
				}
			}
			// What init wired is what render keeps: the next render changes
			// no pointer file.
			before := renderSnapshot(c, "CLAUDE.md", "AGENTS.md", "GEMINI.md", ".cursorrules", ".github/copilot-instructions.md", ".cursor/rules/lore.mdc")
			c.MustLore("render")
			renderSameFiles(t, "render after init", before, renderSnapshot(c, "CLAUDE.md", "AGENTS.md", "GEMINI.md", ".cursorrules", ".github/copilot-instructions.md", ".cursor/rules/lore.mdc"))
		})
	}
}

func TestCampaignRender_InitFolderShapes(t *testing.T) {
	t.Run("not a git repo", func(t *testing.T) {
		w := newWorld(t)
		p := w.Human("person", "person@example.com")
		p.WriteConfig(renderSoloConfig())
		dir := filepath.Join(p.Home, "plain")
		if err := os.MkdirAll(dir, 0o750); err != nil {
			t.Fatal(err)
		}
		p.Lore(dir, "init").Fails(t, campExitGuard, "[E_NOT_A_STORE]", "hint: ", "git init")
		if ents, _ := os.ReadDir(dir); len(ents) != 0 {
			t.Errorf("a refused init leaves the folder empty, found %d entries", len(ents))
		}
	})
	t.Run("read-only checkout", func(t *testing.T) {
		c := campFresh(t)
		if err := os.Chmod(c.Dir, 0o555); err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { _ = os.Chmod(c.Dir, 0o755) }) // t.TempDir must remove it
		before := campTree(t, c.Dir)
		// The cause is the folder, so the person's input to fix: bad
		// input with the folder named and the way out, never E_INTERNAL.
		r := c.Lore("init")
		r.Fails(t, campExitBadInput, "[E_BAD_PATH]", "permission denied", "hint: ", "writable")
		r.Never(t, "E_INTERNAL")
		campSameTree(t, "a refused init writes nothing", before, campTree(t, c.Dir))
	})
	t.Run("nested repo", func(t *testing.T) {
		outer := campFresh(t)
		inner := outer.In("vendor/lib")
		inner.Git("init", "-q")
		inner.MustLore("init", "--name=lib").Says(t, "name:       lib")
		if _, err := os.Stat(filepath.Join(inner.Dir, ".lore")); err != nil {
			t.Fatalf("the inner repo has its own .lore: %v", err)
		}
		if _, err := os.Stat(filepath.Join(outer.Dir, ".lore")); err == nil {
			t.Error("init in a nested repo never makes a project in the outer repo")
		}
		outer.MustLore("init", "--name=tool").Says(t, "name:       tool")
		inner.Lore("init").Fails(t, campExitRefused, "[E_ALREADY_INITIALIZED]")
	})
	t.Run("sub-folder project shares the repo id", func(t *testing.T) {
		c := campFresh(t)
		top := renderID(t, c.MustLore("init", "--name=tool"), "rep")
		sub := c.In("services/billing")
		got := renderID(t, sub.MustLore("init", "--name=billing"), "rep")
		if got != top {
			t.Errorf("one checkout has one repo id: top %s, sub-folder %s", top, got)
		}
		if _, err := os.Stat(filepath.Join(sub.Dir, ".lore")); err != nil {
			t.Errorf("the sub-folder is its own project: %v", err)
		}
	})
	t.Run("init <path>", func(t *testing.T) {
		c := campFresh(t)
		c.WriteFile("pkg/web/README.md", "web\n")
		c.MustLore("init", "pkg/web", "--name=web").Says(t, "name:       web")
		if _, err := os.Stat(filepath.Join(c.Dir, "pkg", "web", ".lore")); err != nil {
			t.Errorf("init <path> roots the project at path: %v", err)
		}
		c.Lore("init", "pkg/missing").Fails(t, campExitBadInput, "[E_BAD_PATH]", "hint: ", "create it first")
	})
	t.Run("twice", func(t *testing.T) {
		c := campFresh(t)
		c.MustLore("init", "--name=tool")
		before := campTree(t, c.Dir)
		for range 2 {
			c.Lore("init", "--name=other").Fails(t, campExitRefused, "[E_ALREADY_INITIALIZED]", "hint: ", "lore doctor")
		}
		campSameTree(t, "a second init writes nothing", before, campTree(t, c.Dir))
	})
}

func TestCampaignRender_InitOddNames(t *testing.T) {
	cases := []struct{ name, flag, want string }{
		{"spaces", "my tool", "my tool"},
		{"upper case is lowered", "My-Tool", "my-tool"},
		{"unicode and emoji", "工具🚀", "工具🚀"},
		{"right to left", "شبكة", "شبكة"},
		{"blank falls back to origin's repo name", "   ", "tool"},
		{"very long", strings.Repeat("x", 10000), strings.Repeat("x", 10000)},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			c := campFresh(t)
			c.MustLore("init", "--name="+tc.flag).Says(t, "name:       "+tc.want+"\n")
			type proj struct {
				Name string `json:"name"`
			}
			got := campJSON[struct {
				Data []proj `json:"data"`
			}](t, c.Lore("project", "list", "--json"))
			found := false
			for _, p := range got.Data {
				found = found || p.Name == tc.want
			}
			if !found {
				t.Errorf("project list names %q: %+v", tc.want[:min(len(tc.want), 40)], got.Data)
			}
		})
	}
}
