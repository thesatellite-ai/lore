// renderIDRe matches a lore row id of any table.
var renderIDRe = regexp.MustCompile(`\b([a-z]{3})_[0-9a-f]{32}\b`)

// renderID is the first <prefix>_ id the command printed.
func renderID(t *testing.T, r th.Result, prefix string) string {
	t.Helper()
	for _, m := range renderIDRe.FindAllStringSubmatch(r.Out(), -1) {
		if m[1] == prefix {
			return m[0]
		}
	}
	t.Fatalf("no %s_ id in output: %s", prefix, r)
	return ""
}

// renderRead reads a file of the clone, failing when it is missing.
func renderRead(t *testing.T, c *th.Clone, rel string) string {
	t.Helper()
	s, ok := c.ReadFile(rel)
	if !ok {
		t.Fatalf("%s is missing", rel)
	}
	return s
}

// renderSnapshot reads every given file ("" for a missing one).
func renderSnapshot(c *th.Clone, rels ...string) map[string]string {
	out := map[string]string{}
	for _, r := range rels {
		s, _ := c.ReadFile(r)
		out[r] = s
	}
	return out
}

// renderSameFiles fails when a file of before changed.
func renderSameFiles(t *testing.T, what string, before, after map[string]string) {
	t.Helper()
	for f, b := range before {
		if after[f] != b {
			t.Errorf("%s: %s changed:\n--- before\n%s\n--- after\n%s", what, f, b, after[f])
		}
	}
}

// renderSection is the text of LORE.md from heading to the next "## "
// heading ("" when the heading is absent).
func renderSection(md, heading string) string {
	i := strings.Index(md, "\n"+heading+"\n")
	if i < 0 {
		return ""
	}
	rest := md[i+1+len(heading):]
	if j := strings.Index(rest, "\n## "); j >= 0 {
		return rest[:j]
	}
	return rest
}

// renderAPI is a running `lore api --port 0` in one clone.
type renderAPI struct {
	base, token string
}

// renderAPIListenRe reads the address from `lore api`'s listening line.
var renderAPIListenRe = regexp.MustCompile(`listening on (http://127\.0\.0\.1:[0-9]+)`)

// renderStartAPI runs `lore api` in c and waits for its listening line;
// the process is killed at cleanup.
func renderStartAPI(t *testing.T, c *th.Clone) *renderAPI {
	t.Helper()
	cmd := c.Command("api", "--port", "0")
	stderr, err := cmd.StderrPipe()
	if err != nil {
		t.Fatal(err)
	}
	cmd.Stdout = io.Discard
	if serr := cmd.Start(); serr != nil {
		t.Fatal(serr)
	}
	t.Cleanup(func() { _ = cmd.Process.Kill(); _ = cmd.Wait() })
	found := make(chan string, 1)
	go func() {
		sc := bufio.NewScanner(stderr)
		var seen []string
		for sc.Scan() {
			seen = append(seen, sc.Text())
			if m := renderAPIListenRe.FindStringSubmatch(sc.Text()); m != nil {
				found <- m[1]
				_, _ = io.Copy(io.Discard, stderr)
				return
			}
		}
		found <- "NOT STARTED: " + strings.Join(seen, " | ")
	}()
	var base string
	select {
	case base = <-found:
	case <-time.After(30 * time.Second):
		t.Fatal("lore api did not print its listening line")
	}
	if !strings.HasPrefix(base, "http://") {
		t.Fatalf("lore api: %s", base)
	}
	tok, err := os.ReadFile(c.A.LorePath("api-token"))
	if err != nil {
		t.Fatal(err)
	}
	return &renderAPI{base: base, token: strings.TrimSpace(string(tok))}
}

// renderReply is one REST answer.
type renderReply struct {
	status int
	code   string
	body   []byte
}

// post sends a JSON body (already encoded) to path with the bearer token.
func (s *renderAPI) post(t *testing.T, path string, body []byte) renderReply {
	t.Helper()
	req, err := http.NewRequest(http.MethodPost, s.base+path, bytes.NewReader(body))
	if err != nil {
		t.Fatal(err)
	}
	req.Header.Set("Authorization", "Bearer "+s.token)
	req.Header.Set("Content-Type", "application/json")
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = resp.Body.Close() }()
	raw, _ := io.ReadAll(resp.Body) // a short read shows in the assertion
	var env struct {
		Error struct {
			Code string `json:"code"`
		} `json:"error"`
	}
	_ = json.Unmarshal(raw, &env) // a success body has no error member
	return renderReply{status: resp.StatusCode, code: env.Error.Code, body: raw}
}

// renderErrCode is the [E_…] code a CLI refusal printed ("" when none).
func renderErrCode(r th.Result) string {
	m := regexp.MustCompile(`\[(E_[A-Z_]+)\]`).FindStringSubmatch(r.Out())
	if m == nil {
		return ""
	}
	return m[1]
}
