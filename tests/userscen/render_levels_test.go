// render_levels_test.go — scope levels and folder files (CONTEXT_BUDGET
// 6.2.3-6.2.7, CQ10, 8.9):
//   - `lore scope show` lists the chain general first (project, repo, dir),
//     text and --json; `lore scope list` names each folder scope;
//   - a folder with context.dir_min_entries (3) pinned entries gets its own
//     <dir>/LORE.md, the root keeps one index line for it, LORE.full.md
//     keeps every entry; a smaller folder folds into the root;
//   - a scope whose folder is missing on disk renders in the root (a must
//     rule is never lost);
//   - when a folder loses its file, lore deletes only a file it generated,
//     never a hand-written LORE.md in that folder;
//   - matrix own repo × client repo: folder files are off in a client repo
//     until set (fail closed: no new files in someone else's repo), and the
//     rules still reach the root LORE.md; setting context.dir_files turns
//     them on.

import (
	"path/filepath"
	"strings"
	"testing"

	th "github.com/thesatellite-ai/lore/tests/teame2e/teamharness"
)

// renderDirHeader opens every folder LORE.md lore writes.
const renderDirHeader = "<!-- generated by lore render; scope dir:"

// renderClientConfig is a person in org "northwind" whose config lists
// github.com/acme/* as client repos (no store: the repo's own rows only).
func renderClientConfig() th.Config {
	return th.Config{
		Personal: &th.Personal{Store: th.PersonalLocal},
		Orgs: []th.Org{{
			Name:     "northwind",
			Identity: th.Identity{Key: "human:person@example.com", Name: "Person Example", Handle: "person"},
			Own:      []string{"github.com/octo-personal/*"},
			Repos:    []string{"github.com/acme/*"},
		}},
		Live: th.FreshFetch(),
	}
}

// renderRepoFor is a lore-initialised clone of slug for one person.
func renderRepoFor(t *testing.T, slug string, cfg th.Config) *th.Clone {
	t.Helper()
	w := newWorld(t)
	p := w.Human("person", "person@example.com")
	p.WriteConfig(cfg)
	c := p.Clone(w.Remote(slug), "repo")
	// --yes: a client repo asks before lore writes into it (I-13); these
	// fixtures set lore up in it on purpose
	c.MustLore("init", "--non-interactive", "--name=repo", "--yes")
	return c
}

// renderBillingRows adds three pinned entries scoped to src/billing (the
// default dir_min_entries), a repo rule and, unless the repo is a client's
// (where project scope means the org's internal project), a project rule.
func renderBillingRows(t *testing.T, c *th.Clone) map[string]string {
	t.Helper()
	ids := renderBillingRowsNoProject(t, c)
	ids["project"] = renderID(t, c.MustLore("rule", "add", "--body", "project wide: log in UTC", "--severity", "must", "--scope", "project"), "rul")
	return ids
}

// renderBillingRowsNoProject is renderBillingRows without the project rule.
func renderBillingRowsNoProject(t *testing.T, c *th.Clone) map[string]string {
	t.Helper()
	c.WriteFile("src/billing/invoice.go", "package billing\n")
	return map[string]string{
		"repo":   renderID(t, c.MustLore("rule", "add", "--body", "repo wide: run the linter", "--severity", "must", "--scope", "repo", "--to", "repo"), "rul"),
		"dir1":   renderID(t, c.MustLore("rule", "add", "--body", "billing: amounts in minor units", "--severity", "must", "--scope", "dir:src/billing", "--to", "repo"), "rul"),
		"dir2":   renderID(t, c.MustLore("rule", "add", "--body", "billing: never round twice", "--severity", "must", "--scope", "dir:src/billing", "--to", "repo"), "rul"),
		"dirhot": renderID(t, c.MustLore("hotfix", "add", "--title", "Invoice crash", "--body", "restart the invoice worker", "--severity", "critical", "--scope", "dir:src/billing", "--to", "repo"), "hfx"),
	}
}

func TestRenderScopeShowChainOrder(t *testing.T) {
	c := renderSolo(t)
	renderBillingRows(t, c)
	r := c.MustLore("scope", "show", "src/billing/invoice.go")
	r.Says(t, "scope chain for src/billing/invoice.go (general first; later wins on conflict)")
	out := r.Stdout
	pi, ri, di := strings.Index(out, "  project "), strings.Index(out, "  repo "), strings.Index(out, "  dir ")
	if pi < 0 || ri < 0 || di < 0 || pi >= ri || ri >= di {
		t.Fatalf("the chain is project, then repo, then dir: %s", out)
	}
	type level struct {
		Scope    string `json:"scope"`
		Name     string `json:"name"`
		Rules    int    `json:"rules"`
		Hotfixes int    `json:"hotfixes"`
		File     string `json:"file"`
	}
	type chain struct {
		Path   string  `json:"path"`
		Levels []level `json:"levels"`
	}
	ch := th.DecodeJSON[chain](t, c.Lore("scope", "show", "src/billing/invoice.go", "--json"))
	if ch.Path != "src/billing/invoice.go" || len(ch.Levels) != 3 {
		t.Fatalf("--json: the path and three levels: %+v", ch)
	}
	want := []level{
		{Scope: "project", Rules: 1, Hotfixes: 0, File: renderLoreMD},
		{Scope: "repo", Rules: 1, Hotfixes: 0, File: renderLoreMD},
		{Scope: "dir", Name: "src/billing", Rules: 2, Hotfixes: 1},
	}
	for i, w := range want {
		g := ch.Levels[i]
		if g.Scope != w.Scope || g.Rules != w.Rules || g.Hotfixes != w.Hotfixes || (w.File != "" && g.File != w.File) || (w.Name != "" && g.Name != w.Name) {
			t.Errorf("level %d: got %+v, want %+v", i, g, w)
		}
	}
	// After render the dir level names its folder file.
	c.MustLore("render")
	ch = th.DecodeJSON[chain](t, c.Lore("scope", "show", "src/billing/invoice.go", "--json"))
	if got := ch.Levels[2].File; got != "src/billing/LORE.md" {
		t.Errorf("after render the dir level is served by src/billing/LORE.md: %q", got)
	}
	// A path outside any folder scope: no dir level.
	ch = th.DecodeJSON[chain](t, c.Lore("scope", "show", "README.md", "--json"))
	for _, l := range ch.Levels {
		if l.Scope == "dir" {
			t.Errorf("README.md is in no folder scope: %+v", ch.Levels)
		}
	}
	c.MustLore("scope", "list").Says(t, "dir:src/billing", "src/billing/LORE.md")
}

func TestRenderFolderFileOwnRepo(t *testing.T) {
	c := renderSolo(t)
	ids := renderBillingRows(t, c)
	c.MustLore("render").Says(t, filepath.FromSlash("src/billing/LORE.md"))
	dir := renderRead(t, c, "src/billing/LORE.md")
	if !strings.HasPrefix(dir, renderDirHeader+"src/billing") {
		t.Fatalf("the folder file starts with lore's header: %q", dir[:min(len(dir), 120)])
	}
	for _, k := range []string{"dir1", "dir2", "dirhot"} {
		if !strings.Contains(dir, ids[k]) {
			t.Errorf("the folder file holds %s", k)
		}
	}
	for _, k := range []string{"project", "repo"} {
		if strings.Contains(dir, ids[k]) {
			t.Errorf("the folder file holds only its folder's entries, not the %s rule", k)
		}
	}
	root := renderRead(t, c, renderLoreMD)
	for _, k := range []string{"project", "repo"} {
		if !strings.Contains(root, ids[k]) {
			t.Errorf("the root LORE.md has the %s rule", k)
		}
	}
	if strings.Contains(root, "billing: amounts in minor units") {
		t.Error("the folder's rule bodies live in the folder file, not the root")
	}
	if !strings.Contains(root, "## Folder files") || !strings.Contains(root, "- src/billing: 2 must rules, 1 hotfix;") {
		t.Errorf("the root indexes the folder file: %s", renderSection(root, "## Folder files"))
	}
	full := renderRead(t, c, renderFullMD)
	for k, id := range ids {
		if !strings.Contains(full, id) {
			t.Errorf("LORE.full.md keeps every scope's entry (%s)", k)
		}
	}
	// lore context for a file there names the folder rules.
	c.MustLore("context", "--for-file", "src/billing/invoice.go").Says(t, ids["dir1"], ids["dirhot"], "scope dir:src/billing")

	// The folder drops under dir_min_entries: its generated file goes and
	// its entries return to the root.
	c.MustLore("rule", "delete", ids["dir2"], "--yes")
	c.MustLore("render")
	if _, ok := c.ReadFile("src/billing/LORE.md"); ok {
		t.Error("a folder under dir_min_entries loses its generated file")
	}
	root = renderRead(t, c, renderLoreMD)
	if !strings.Contains(root, "billing: amounts in minor units") || strings.Contains(root, "## Folder files") {
		t.Errorf("the folder's entries are back in the root, no folder index: %s", root)
	}
}

func TestRenderHandWrittenFolderFileNeverDeleted(t *testing.T) {
	c := renderSolo(t)
	ids := renderBillingRows(t, c)
	hand := "# Billing notes\n\nwritten by a person\n"
	c.WriteFile("src/billing/LORE.md", hand)
	c.MustLore("render").Says(t, "src/billing/LORE.md is not lore's (no generated header), so render leaves it as is and keeps dir:src/billing's entries in .lore/LORE.md")
	if got := renderRead(t, c, "src/billing/LORE.md"); got != hand {
		t.Fatalf("render never overwrites a person's own folder LORE.md: %q", got)
	}
	// Its folder's entries are not lost: they stay in the root file.
	root := renderRead(t, c, renderLoreMD)
	for _, k := range []string{"dir1", "dir2", "dirhot"} {
		if !strings.Contains(root, ids[k]) {
			t.Errorf("the folder's %s is in the root LORE.md while its LORE.md is hand-written", k)
		}
	}
	if strings.Contains(root, "## Folder files") {
		t.Error("no folder-file index line for a folder lore does not write")
	}
	c.MustLore("render").Says(t, "· .lore/LORE.md (unchanged)")
	if got := renderRead(t, c, "src/billing/LORE.md"); got != hand {
		t.Fatalf("a second render leaves it too: %q", got)
	}
	// The folder loses its file: the person's text is still there.
	c.MustLore("rule", "delete", ids["dir2"], "--yes")
	c.MustLore("render")
	after, ok := c.ReadFile("src/billing/LORE.md")
	if !ok || !strings.Contains(after, "written by a person") {
		t.Fatalf("a hand-written folder LORE.md is never deleted: %q (exists %v)", after, ok)
	}
}

func TestRenderMissingFolderFallsBackToRoot(t *testing.T) {
	c := renderSolo(t)
	ids := renderBillingRows(t, c)
	c.Git("rm", "-q", "-r", "--cached", "--ignore-unmatch", "src")
	c.TryGit("clean", "-q", "-fdx", "src")
	if _, ok := c.ReadFile("src/billing/invoice.go"); ok {
		t.Fatal("fixture: the folder is gone")
	}
	c.MustLore("render")
	root := renderRead(t, c, renderLoreMD)
	for _, k := range []string{"dir1", "dir2", "dirhot"} {
		if !strings.Contains(root, ids[k]) {
			t.Errorf("a rule of a missing folder is never lost: %s goes to the root", k)
		}
	}
	if _, ok := c.ReadFile("src/billing/LORE.md"); ok {
		t.Error("no folder file is created for a missing folder")
	}
}

func TestRenderFolderFilesOwnVsClient(t *testing.T) {
	scenParallel(t) // its sub-tests each build their own World and run in parallel
	cases := []struct {
		name       string
		slug       string
		cfg        th.Config
		folderFile bool
	}{
		{"own repo", renderSlugOwn, renderSoloConfig(), true},
		{"client repo", renderSlugClient, renderClientConfig(), false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			c := renderRepoFor(t, tc.slug, tc.cfg)
			ids := renderBillingRowsNoProject(t, c)
			c.MustLore("render")
			_, has := c.ReadFile("src/billing/LORE.md")
			if has != tc.folderFile {
				t.Fatalf("%s: folder file written = %v, want %v", tc.name, has, tc.folderFile)
			}
			root := renderRead(t, c, renderLoreMD)
			if !tc.folderFile {
				for _, k := range []string{"dir1", "dir2", "dirhot"} {
					if !strings.Contains(root, ids[k]) {
						t.Errorf("client repo: the folder's %s is in the root LORE.md", k)
					}
				}
				c.MustLore("render", "--report").Says(t, "folder files: off (context.dir_files; a client repo is off until set for that client)")
				// Set for this client: folder files appear.
				c.MustLore("policy", "set", "context.dir_files", "true", "--yes")
				c.MustLore("render")
				if _, ok := c.ReadFile("src/billing/LORE.md"); !ok {
					t.Error("client repo with context.dir_files true gets its folder file")
				}
			}
			// Nothing lore writes in the checkout names the person's private
			// render dir.
			if f := c.LeakScan(c.A.LorePath("render")); len(f) != 0 {
				t.Errorf("no committed file names the private render folder: %v", f)
			}
		})
	}
}
