//go:build journeys && !windows

package journeys

// orphanrender_test.go — devco:S-1: a repo whose committed .lore/LORE.md an
// older lore rendered (no .lore/data rows, no lore.db here). Ida's lore
// init says the file is kept and how to bring its rows in; her lore render
// keeps it byte for byte instead of writing an empty file over the team's
// pinned rule and hotfix. Once she removes it, render starts fresh.

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// orphanLoreMD is the committed file: an older lore's header, one must
// rule and one high hotfix whose rows are in that lore's db only.
const orphanLoreMD = `<!-- AICODER:CANARY=rnd_1141dffa21f73935 SCHEMA=v1 -->
<!-- This file is generated by lore render. Do not edit by hand. -->

## Must rules

<rule id="rul_019f22dfe48c72bf8fb85d0e251497c9" severity="must" trust="0.50">
Always develop on dev; promote dev to staging to main by merge only
</rule>

<hotfix id="hfx_019f322aff377e059d863195e81c3e5b" severity="high">
Flush the cache before the staging deploy
</hotfix>
`

func TestJourneyOrphanLoreMDKept(t *testing.T) {
	t.Parallel()
	w := NewWorld(t)
	ida := w.Persona("Ida Lund", "ida@example.test").Laptop()
	repo := w.Remote("github.com/acme-or/app")
	ic := ida.Clone(repo, "app")
	w.Step("day1/committed-old-render", func() {
		ic.WriteFile(".lore/LORE.md", orphanLoreMD)
		if err := os.Chmod(filepath.Join(ic.Dir, ".lore", "LORE.md"), 0o644); err != nil { // a committed file is readable
			t.Fatal(err)
		}
		ic.WriteFile("CLAUDE.md", "# app\n\n@.lore/LORE.md\n")
		fpCommitPush(t, ic, "notes from the old lore")
	})
	w.Step("day1/init-and-render-keep-it", func() {
		ida.LoreIn(ic, "init", "--name", "app").OK(t).Says(t, ".lore/LORE.md kept as it is", "2 entries (1 hotfix, 1 rule)", "lore migrate run")
		ida.LoreIn(ic, "render").OK(t).Says(t, ".lore/LORE.md kept as it is", "git rm .lore/LORE.md")
		if got, _ := ic.ReadFile(".lore/LORE.md"); got != orphanLoreMD {
			t.Fatalf("render replaced the committed LORE.md whose rows are not here:\n%s", got)
		}
	})
	w.Step("day1/start-fresh", func() {
		ic.Git("rm", "-q", ".lore/LORE.md")
		ida.LoreIn(ic, "render").OK(t).Never(t, "kept as it is")
		if got, _ := ic.ReadFile(".lore/LORE.md"); strings.Contains(got, "rul_019f22dfe48c72bf8fb85d0e251497c9") || got == "" {
			t.Fatalf("a fresh render after git rm is not today's empty render:\n%s", got)
		}
	})
}
