var teDCanaryRe = regexp.MustCompile(`rnd_[0-9a-f]{16}`)

// teDGolden fills the placeholders of a golden.
func teDGolden(golden string, ids map[string]string) string {
	out := strings.ReplaceAll(golden, "~", "`")
	for name, id := range ids {
		out = strings.ReplaceAll(out, "{"+name+"}", id)
	}
	return out
}

func TestTeD_RenderGoldenTwoClones(t *testing.T) {
	bc, carol := teDSoloPair(t, th.Cmd("render"), th.Cmd("policy", "set"))
	bc.MustLore("init", "--non-interactive", "--name=tool")
	ids := map[string]string{
		"MUST": mustID(t, bc.MustLore("rule", "add", "--body", "run the tests before you push", "--severity", "must"), "rul"),
		"CRIT": mustID(t, bc.MustLore("hotfix", "add", "--title", "Login 500 after deploy", "--body", "clear the session cache after a deploy", "--severity", "critical"), "hfx"),
		"HIGH": mustID(t, bc.MustLore("hotfix", "add", "--title", "Flaky CI", "--body", "rerun the job once", "--severity", "high"), "hfx"),
	}
	bc.MustLore("rule", "add", "--body", "prefer small commits", "--severity", "should")
	bc.MustLore("hotfix", "add", "--title", "Slow lint", "--body", "lint only changed files", "--severity", "medium")
	bc.MustLore("memory", "add", "--body", "the parser lives in internal/parse")
	bc.MustLore("decision", "add", "--title", "Postgres over MySQL", "--body", "we need jsonb")
	bc.MustLore("policy", "set", "context.targets", "claude_code,codex", "--yes")
	bc.MustLore("render").Says(t, "budget 16000 codex")
	bc.CommitAll("lore")
	bc.AdminPush("origin", "main")

	lore, _ := bc.ReadFile(".lore/LORE.md")
	canary := teDCanaryRe.FindString(lore)
	if canary == "" {
		t.Fatalf("LORE.md carries the canary: %s", lore)
	}
	ids["CANARY"] = canary
	want := map[string]string{
		".lore/LORE.md":      teDGolden(teDGoldenLore, ids),
		".lore/LORE.full.md": teDGolden(teDGoldenFull, ids),
		"CLAUDE.md":          teDGolden(teDGoldenClaude, ids),
		"AGENTS.md":          teDGolden(teDGoldenAgents, ids),
	}
	for f, w := range want {
		if got, _ := bc.ReadFile(f); got != w {
			t.Errorf("bob's %s differs from the golden:\n--- got\n%s\n--- want\n%s", f, got, w)
		}
	}

	// carol's clone renders the same bytes: nothing to commit.
	cc := carol.Clone(bc.Remote, "tool")
	cc.MustLore("render")
	if st := cc.Status(); st != "" {
		t.Fatalf("a teammate's render of the same rows changes no committed file: %q", st)
	}
	for f, w := range want {
		if got, _ := cc.ReadFile(f); got != w {
			t.Errorf("carol's %s differs from the golden", f)
		}
	}
}
