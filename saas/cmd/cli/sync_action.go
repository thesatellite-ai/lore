package main

// `lore sync install-action` / `uninstall-action` — opt-in GitHub workflow
// that runs `lore sync ci-merge` for pull requests (see sync_ci.go for why).
//
// Opt-in on purpose: the workflow spends Actions time, which is billed on
// private repositories, so lore never installs it on its own (unlike the
// local git hooks). The file is generated from sync_action.yml.tmpl with the
// same constants the CLI uses (driver outcomes, data paths), so the workflow
// and the binary it downloads cannot drift apart.
//
// Keeping the pin current: a file installed without --lore-version is pinned
// "auto". Every lore command checks it (refreshSyncActionPin, run with the
// git wiring) and, when the running lore is a newer release, rewrites the
// file to that release and asks the developer to commit it. It never
// downgrades, never touches a "fixed" pin or a hand-edited file (detected by
// the checksum line), and never acts from a development build.

