package main

// `lore sync install-action` / `uninstall-action` — opt-in GitHub workflow
// that runs `lore sync ci-merge` for pull requests (see sync_ci.go for why).
//
// Opt-in on purpose: the workflow spends Actions time, which is billed on
// private repositories, so lore never installs it on its own (unlike the
// local git hooks). The file is generated from sync_action.yml.tmpl with the
// same constants the CLI uses (driver outcomes, data paths), so the workflow
// and the binary it downloads cannot drift apart; re-running install-action
// after a lore upgrade refreshes it.

import (
	"bytes"
	"context"
	_ "embed"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"strings"
	"text/template"

	"github.com/spf13/cobra"

	"saas/pkg/aicoder/errcodes"
	"saas/pkg/aicoder/gitsetup"
	"saas/pkg/aicoder/style"
	"saas/pkg/constants"
)

//go:embed sync_action.yml.tmpl
var syncActionTemplate string

// syncActionMarker opens every generated workflow file. install-action only
// overwrites, and uninstall-action only deletes, a file that starts with it.
const syncActionMarker = "# lore-sync-merge: generated by `lore sync install-action`"

// syncActionRel is where the workflow lives, relative to the repository root
// (GitHub only reads workflows from there, wherever the lore project is).
var syncActionRel = path.Join(".github", "workflows", "lore-sync-merge.yml")

// loreReleaseRepo is the GitHub repository lore releases are published from;
// the workflow downloads the lore binary from its releases.
const loreReleaseRepo = "thesatellite-ai/lore"

// loreVersionLatest asks the workflow for the newest release instead of a
// pinned one.
const loreVersionLatest = "latest"

// fallbackDefaultBranch is used when the clone never recorded the remote's
// default branch and no --branch was given.
const fallbackDefaultBranch = "main"

// syncActionRemote is the remote whose default branch is looked up.
const syncActionRemote = "origin"

// syncActionDirMode is the mode of a created .github/workflows directory.
const syncActionDirMode = 0o755

// syncActionFileMode is the mode of the written workflow file.
const syncActionFileMode = 0o644

// releaseVersionPattern matches a lore version that has a published release
// (what goreleaser stamps into release builds: "0.1.10" or "v0.1.10").
// Development builds ("0.1.0-dev", "v0.1.9-4-gabc-dirty") do not.
var releaseVersionPattern = regexp.MustCompile(`^v?\d+\.\d+\.\d+$`)

// branchNamePattern accepts the branch names install-action writes into the
// workflow; anything else is refused rather than escaped into YAML.
var branchNamePattern = regexp.MustCompile(`^[A-Za-z0-9._/-]+$`)

// syncActionParams fills sync_action.yml.tmpl.
type syncActionParams struct {
	// Marker is syncActionMarker (first line of the file).
	Marker string
	// LoreVersion is the release tag ("v0.1.10") or loreVersionLatest.
	LoreVersion string
	// ReleaseURL is the base URL of that release's assets.
	ReleaseURL string
	// Manual drops the automatic triggers (workflow_dispatch only).
	Manual bool
	// DataGlob is the paths filter for lore data, repository-relative.
	DataGlob string
	// BranchesYAML is the YAML flow sequence of branches whose pushes
	// trigger the job.
	BranchesYAML string
	// DefaultBranch is the workflow_dispatch input's default.
	DefaultBranch string
	// WorkDir is the lore project directory, repository-relative ("." at
	// the root); ci-merge runs there.
	WorkDir string
	// OutcomeMerged / OutcomeNeedsHuman are the ci-merge outcomes the job
	// branches on.
	OutcomeMerged     string
	OutcomeNeedsHuman string
}

// syncActionOptions are install-action's inputs.
type syncActionOptions struct {
	branches    []string
	manual      bool
	loreVersion string
	dryRun      bool
	force       bool
}

// syncActionResult is what install-action / uninstall-action report.
type syncActionResult struct {
	// Path is the workflow file.
	Path string `json:"path"`
	// Status is one of the syncAction* status constants.
	Status string `json:"status"`
	// LoreVersion is the lore release the workflow downloads.
	LoreVersion string `json:"lore_version,omitempty"`
	// Branches are the branches whose pushes trigger it (none when manual).
	Branches []string `json:"branches,omitempty"`
	// Manual is true when the workflow only runs by hand.
	Manual bool `json:"manual"`
	// Content is the generated file (--dry-run only).
	Content string `json:"content,omitempty"`
}

// install-action / uninstall-action statuses.
const (
	syncActionCreated   = "created"
	syncActionUpdated   = "updated"
	syncActionUnchanged = "unchanged"
	syncActionDryRun    = "dry-run"
	syncActionRemoved   = "removed"
	syncActionAbsent    = "not-installed"
)

// jsonKindSyncAction is the JSON envelope kind of both commands.
const jsonKindSyncAction = "sync.action"

func newSyncInstallActionCommand() *cobra.Command {
	var o syncActionOptions
	var asJSON bool
	cmd := &cobra.Command{
		Use:   "install-action",
		Short: "Add a GitHub workflow that merges lore data in pull requests (opt-in)",
		Long: `Writes .github/workflows/lore-sync-merge.yml at the repository root.

GitHub's merge button never runs lore's merge driver, so two pull requests
that edited the same lore row conflict there even when lore would merge them.
The workflow runs ` + "`lore sync ci-merge`" + ` for open pull requests: it merges the base
branch in with lore and pushes, only when every conflict is in lore data and
lore settles all of them. Anything else is left for a person.

It runs when lore data changes on a pull request or on a --branch (default:
the remote's default branch). It uses Actions time (billed on private
repositories); --manual installs it to run only when started by hand.

Re-run after upgrading lore to refresh it. Commit the file to enable it.`,
		Example: `  lore sync install-action
  lore sync install-action --branch main --branch staging
  lore sync install-action --manual
  lore sync install-action --dry-run`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			res, err := installSyncAction(cmd.Context(), ".", o)
			if err != nil {
				return err
			}
			if asJSON {
				printJSON(jsonKindSyncAction, res, 0)
				return nil
			}
			printSyncAction(res)
			return nil
		},
	}
	cmd.Flags().StringArrayVar(&o.branches, constants.FlagBranch, nil, "branch whose pushes trigger the workflow (repeatable; default: the remote's default branch)")
	cmd.Flags().BoolVar(&o.manual, constants.FlagManual, false, "run only when started by hand (no automatic triggers)")
	cmd.Flags().StringVar(&o.loreVersion, constants.FlagLoreVersion, "", "lore release the workflow downloads: vX.Y.Z or latest (default: this lore's version)")
	cmd.Flags().BoolVar(&o.dryRun, constants.FlagDryRun, false, "print the workflow; write nothing")
	cmd.Flags().BoolVar(&o.force, constants.FlagForce, false, "overwrite a file at that path that lore did not generate")
	cmd.Flags().BoolVar(&asJSON, constants.FlagJSON, false, "JSON output")
	return cmd
}

func newSyncUninstallActionCommand() *cobra.Command {
	var force, asJSON bool
	cmd := &cobra.Command{
		Use:     "uninstall-action",
		Short:   "Remove the workflow added by install-action",
		Long:    "Deletes .github/workflows/lore-sync-merge.yml if lore generated it. Commit the deletion to disable it.",
		Example: "  lore sync uninstall-action",
		Args:    cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			res, err := uninstallSyncAction(cmd.Context(), ".", force)
			if err != nil {
				return err
			}
			if asJSON {
				printJSON(jsonKindSyncAction, res, 0)
				return nil
			}
			printSyncAction(res)
			return nil
		},
	}
	cmd.Flags().BoolVar(&force, constants.FlagForce, false, "delete the file even if lore did not generate it")
	cmd.Flags().BoolVar(&asJSON, constants.FlagJSON, false, "JSON output")
	return cmd
}

// installSyncAction renders and writes the workflow for the project at dir.
func installSyncAction(ctx context.Context, dir string, o syncActionOptions) (syncActionResult, error) {
	repo, err := gitsetup.Open(ctx, dir)
	if err != nil {
		return syncActionResult{}, errcodes.New(errcodes.Unsupported, "install-action needs a git repository").WithCause(err)
	}
	params, err := syncActionParamsFor(ctx, repo.Toplevel, dir, o)
	if err != nil {
		return syncActionResult{}, err
	}
	content, err := renderSyncAction(params)
	if err != nil {
		return syncActionResult{}, errcodes.New(errcodes.Internal, "render workflow").WithCause(err)
	}
	file := filepath.Join(repo.Toplevel, filepath.FromSlash(syncActionRel))
	res := syncActionResult{Path: file, LoreVersion: params.LoreVersion, Manual: o.manual}
	if !o.manual {
		res.Branches = branchesOrDefault(ctx, dir, o.branches)
	}
	if o.dryRun {
		res.Status, res.Content = syncActionDryRun, content
		return res, nil
	}
	existing, err := os.ReadFile(file)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		res.Status = syncActionCreated
	case err != nil:
		return res, errcodes.New(errcodes.Internal, "read "+file).WithCause(err)
	case string(existing) == content:
		res.Status = syncActionUnchanged
		return res, nil
	case !strings.HasPrefix(string(existing), syncActionMarker) && !o.force:
		return res, errcodes.New(errcodes.AlreadyInitialized, file+" exists and was not generated by lore").
			WithHint("move it away, or pass --force to overwrite it")
	default:
		res.Status = syncActionUpdated
	}
	if err := os.MkdirAll(filepath.Dir(file), syncActionDirMode); err != nil {
		return res, errcodes.New(errcodes.Internal, "create "+filepath.Dir(file)).WithCause(err)
	}
	if err := os.WriteFile(file, []byte(content), syncActionFileMode); err != nil {
		return res, errcodes.New(errcodes.Internal, "write "+file).WithCause(err)
	}
	return res, nil
}

// uninstallSyncAction deletes the generated workflow.
func uninstallSyncAction(ctx context.Context, dir string, force bool) (syncActionResult, error) {
	repo, err := gitsetup.Open(ctx, dir)
	if err != nil {
		return syncActionResult{}, errcodes.New(errcodes.Unsupported, "uninstall-action needs a git repository").WithCause(err)
	}
	file := filepath.Join(repo.Toplevel, filepath.FromSlash(syncActionRel))
	res := syncActionResult{Path: file}
	existing, err := os.ReadFile(file)
	if errors.Is(err, fs.ErrNotExist) {
		res.Status = syncActionAbsent
		return res, nil
	}
	if err != nil {
		return res, errcodes.New(errcodes.Internal, "read "+file).WithCause(err)
	}
	if !strings.HasPrefix(string(existing), syncActionMarker) && !force {
		return res, errcodes.New(errcodes.InvalidInput, file+" was not generated by lore; refusing to delete it").
			WithHint("pass --force to delete it anyway")
	}
	if err := os.Remove(file); err != nil {
		return res, errcodes.New(errcodes.Internal, "remove "+file).WithCause(err)
	}
	res.Status = syncActionRemoved
	return res, nil
}

// syncActionParamsFor validates options and derives the template inputs.
func syncActionParamsFor(ctx context.Context, toplevel, dir string, o syncActionOptions) (syncActionParams, error) {
	ver, err := workflowLoreVersion(o.loreVersion, version)
	if err != nil {
		return syncActionParams{}, err
	}
	branches := branchesOrDefault(ctx, dir, o.branches)
	for _, b := range branches {
		if !branchNamePattern.MatchString(b) {
			return syncActionParams{}, errcodes.New(errcodes.InvalidInput, fmt.Sprintf("branch name %q has characters install-action does not write into a workflow", b))
		}
	}
	branchesYAML, err := json.Marshal(branches) // a JSON array is a valid YAML flow sequence
	if err != nil {
		return syncActionParams{}, errcodes.New(errcodes.Internal, "encode branches").WithCause(err)
	}
	prefix := lorePathPrefix(toplevel, dir)
	workDir := strings.TrimSuffix(prefix, "/")
	if workDir == "" {
		workDir = repoRootRel
	}
	return syncActionParams{
		Marker:            syncActionMarker,
		LoreVersion:       ver,
		ReleaseURL:        releaseAssetURL(ver),
		Manual:            o.manual,
		DataGlob:          prefix + dataRel + "/**",
		BranchesYAML:      string(branchesYAML),
		DefaultBranch:     branches[0],
		WorkDir:           workDir,
		OutcomeMerged:     ciMergeMerged,
		OutcomeNeedsHuman: ciMergeNeedsHuman,
	}, nil
}

// branchesOrDefault returns the requested branches, or the remote's default
// branch (fallbackDefaultBranch when the clone never recorded one).
func branchesOrDefault(ctx context.Context, dir string, requested []string) []string {
	if len(requested) > 0 {
		return requested
	}
	if b, ok := gitsetup.DefaultBranch(ctx, dir, syncActionRemote); ok {
		return []string{b}
	}
	return []string{fallbackDefaultBranch}
}

// workflowLoreVersion picks the release the workflow downloads: the flag when
// given, else this binary's own version when it is a published release, else
// the latest release (a development build has no release to pin to).
func workflowLoreVersion(flag, own string) (string, error) {
	pick := func(v string) string { return "v" + strings.TrimPrefix(v, "v") }
	switch {
	case flag == loreVersionLatest:
		return loreVersionLatest, nil
	case flag != "":
		if !releaseVersionPattern.MatchString(flag) {
			return "", errcodes.New(errcodes.InvalidInput, fmt.Sprintf("--%s %q: want vX.Y.Z or %s", constants.FlagLoreVersion, flag, loreVersionLatest))
		}
		return pick(flag), nil
	case releaseVersionPattern.MatchString(own):
		return pick(own), nil
	default:
		return loreVersionLatest, nil
	}
}

// releaseAssetURL is the base URL of a release's downloadable assets.
func releaseAssetURL(ver string) string {
	base := "https://github.com/" + loreReleaseRepo + "/releases"
	if ver == loreVersionLatest {
		return base + "/latest/download"
	}
	return base + "/download/" + ver
}

// renderSyncAction fills the template. It uses [[ ]] delimiters because the
// workflow itself is full of GitHub's ${{ }} expressions.
func renderSyncAction(p syncActionParams) (string, error) {
	tmpl, err := template.New("workflow").Delims("[[", "]]").Option("missingkey=error").Parse(syncActionTemplate)
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, p); err != nil {
		return "", err
	}
	return buf.String(), nil
}

// printSyncAction renders an install/uninstall result for a terminal.
func printSyncAction(res syncActionResult) {
	switch res.Status {
	case syncActionDryRun:
		fmt.Print(res.Content)
		return
	case syncActionAbsent:
		fmt.Printf("· no lore workflow at %s\n", res.Path)
		return
	case syncActionRemoved:
		fmt.Printf("%s removed %s — commit the deletion to disable it\n", style.Success("✓"), res.Path)
		return
	case syncActionUnchanged:
		fmt.Printf("· %s is already up to date\n", res.Path)
		return
	}
	fmt.Printf("%s %s %s\n", style.Success("✓"), res.Status, res.Path)
	fmt.Printf("  downloads lore %s\n", res.LoreVersion)
	if res.Manual {
		fmt.Println("  runs only when started by hand (Actions → lore sync merge → Run workflow)")
	} else {
		fmt.Printf("  runs when lore data changes on a pull request or on: %s\n", strings.Join(res.Branches, ", "))
	}
	fmt.Println("  commit the file to enable it; add a LORE_SYNC_TOKEN secret if required checks must re-run on its merges")
}
