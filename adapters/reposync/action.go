package reposync

// action.go — `lore sync install-action`: the opt-in GitHub workflow that
// runs `lore sync ci-merge` for pull requests (see ci.go for why). Ported
// from saas/cmd/cli sync_action.go (LORE_TEAM_SPEC command table); the
// uninstall command is dropped (p3/dropped.md): deleting the file does it.
//
// Opt-in on purpose: the workflow spends Actions time, which is billed on
// private repositories, so lore never installs it on its own (unlike the
// local git hooks). For the same reason a new install only runs when started
// by hand (workflow_dispatch); --auto adds the pull_request and push
// triggers. Re-running install-action, and the pin refresh below, keep the
// triggers an installed file already has unless --auto or --manual is given,
// so nobody's workflow starts or stops spending minutes without asking. The file is generated from sync_action.yml.tmpl with the
// same constants the CLI uses (driver outcomes, data paths), so the workflow
// and the binary it downloads cannot drift apart.
//
// Keeping the pin current: a file installed without --lore-version is pinned
// "auto". Every lore command checks it (refreshSyncActionPin, run with the
// git wiring) and, when the running lore is a newer release, rewrites the
// file to that release and asks the developer to commit it. It never
// downgrades, never touches a "fixed" pin or a hand-edited file (detected by
// the checksum line), and never acts from a development build.

import (
	"bytes"
	"context"
	"crypto/sha256"
	_ "embed"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"text/template"

	"gopkg.in/yaml.v3"

	"github.com/thesatellite-ai/lore/model/errs"
)

//go:embed action.yml.tmpl
var syncActionTemplate string

// syncActionMarker opens every generated workflow file. install-action only
// overwrites a file that starts with it (without --force).
const syncActionMarker = "# lore-sync-merge: generated by `lore sync install-action`"

// syncActionDir is where workflows live, relative to the repository root
// (GitHub only reads workflows from there, wherever the lore project is).
var syncActionDir = path.Join(".github", "workflows")

// syncActionBaseName names the workflow of a lore project at the repository
// root; a project in a subfolder gets "<base>-<folder-slug>.yml", so two lore
// projects in one repository (a monorepo) never overwrite each other's file.
const syncActionBaseName = "lore-sync-merge"

// syncActionExt is the workflow file extension.
const syncActionExt = ".yml"

// syncActionFileRel is the repository-relative workflow path for the lore
// project whose path prefix (lorePathPrefix: "" or "svc/api/") is given.
func syncActionFileRel(prefix string) string {
	return path.Join(syncActionDir, syncActionBaseName+syncActionSlug(prefix)+syncActionExt)
}

// syncActionSlug is "" for the root project, else "-" plus the folder path
// with slashes as dashes ("svc/api/" → "-svc-api"). It also keeps the
// workflow's concurrency group distinct per project.
func syncActionSlug(prefix string) string {
	s := strings.Trim(strings.ReplaceAll(prefix, "/", "-"), "-")
	if s == "" {
		return ""
	}
	return "-" + s
}

// syncActionPin says whether lore may move the workflow's lore version.
type syncActionPin string

const (
	// syncActionPinAuto: installed without --lore-version; follows the
	// newest lore release a developer runs in the repository.
	syncActionPinAuto syncActionPin = "auto"
	// syncActionPinFixed: installed with --lore-version (including
	// "latest"); never changed automatically.
	syncActionPinFixed syncActionPin = "fixed"
)

// Header lines written under the marker. The checksum covers the whole file
// except its own line, with line endings normalised to LF (a Windows
// checkout with CRLF is not a hand edit).
const (
	syncActionPinPrefix = "# lore-sync-merge-pin: "
	syncActionSumPrefix = "# lore-sync-merge-sum: "
	// syncActionSumPending is written while rendering, then replaced by the
	// real checksum of the rendered file.
	syncActionSumPending = "pending"
)

// syncActionMarkerVersion reads "(lore v0.1.11)" / "(lore latest)" from the
// marker line.
var syncActionMarkerVersion = regexp.MustCompile(`\(lore (v\d+\.\d+\.\d+|` + loreVersionLatest + `)\)`)

// loreReleaseRepo is the GitHub repository lore releases are published from;
// the workflow downloads the lore binary from its releases.
const loreReleaseRepo = "thesatellite-ai/lore"

// loreVersionLatest asks the workflow for the newest release instead of a
// pinned one.
const loreVersionLatest = "latest"

// Flag names the messages quote (ops/sync InstallActionIn).
const (
	flagAuto        = "auto"
	flagManual      = "manual"
	flagLoreVersion = "lore-version"
)

// File modes of the workflow file and its folder: what git itself uses for
// a work tree (the file is committed and read by everyone).
const (
	syncDirMode  = 0o755
	syncFileMode = 0o644
)

// fallbackDefaultBranch is used when the clone never recorded the remote's
// default branch and no --branch was given.
const fallbackDefaultBranch = "main"

// syncActionRemote is the remote whose default branch is looked up.
const syncActionRemote = "origin"

// releaseVersionPattern matches a lore version that has a published release
// (what goreleaser stamps into release builds: "0.1.10" or "v0.1.10").
// Development builds ("0.1.0-dev", "v0.1.9-4-gabc-dirty") do not.
var releaseVersionPattern = regexp.MustCompile(`^v?\d+\.\d+\.\d+$`)

// branchNamePattern accepts the branch names install-action writes into the
// workflow; anything else is refused rather than escaped into YAML.
var branchNamePattern = regexp.MustCompile(`^[A-Za-z0-9._/-]+$`)

// syncActionParams fills sync_action.yml.tmpl.
type syncActionParams struct {
	// Marker is syncActionMarker (first line of the file).
	Marker string
	// PinLine records the syncActionPin ("# lore-sync-merge-pin: auto").
	PinLine string
	// SumLine holds the checksum; renderSyncAction fills it in.
	SumLine string
	// NameSuffix and Slug tell projects in subfolders apart: the workflow's
	// display name (" (svc/api)") and its concurrency group ("-svc-api").
	NameSuffix string
	Slug       string
	// LoreVersion is the release tag ("v0.1.10") or loreVersionLatest.
	LoreVersion string
	// ReleaseURL is the base URL of that release's assets.
	ReleaseURL string
	// Manual drops the automatic triggers (workflow_dispatch only).
	Manual bool
	// DataGlob is the paths filter for lore data, repository-relative.
	DataGlob string
	// BranchesYAML is the YAML flow sequence of branches whose pushes
	// trigger the job.
	BranchesYAML string
	// DefaultBranch is the workflow_dispatch input's default.
	DefaultBranch string
	// WorkDir is the lore project directory, repository-relative ("." at
	// the root); ci-merge runs there.
	WorkDir string
	// CIMergeCommand is CIMergeCommand, the command the merge step runs.
	CIMergeCommand string
	// OutcomeMerged / OutcomeNeedsHuman are the ci-merge outcomes the job
	// branches on.
	OutcomeMerged     Outcome
	OutcomeNeedsHuman Outcome
}

// syncActionOptions are install-action's inputs.
type syncActionOptions struct {
	branches []string
	// manual is the resolved trigger choice that syncActionParamsFor
	// renders: true writes workflow_dispatch only. installSyncAction sets
	// it from auto / manualSet / the installed file (resolveSyncActionManual).
	manual bool
	// auto is --auto: add the pull_request and push triggers.
	auto bool
	// manualSet is --manual given explicitly: workflow_dispatch only, even
	// over an installed workflow that has automatic triggers.
	manualSet   bool
	loreVersion string
	// pin defaults to auto; installSyncAction sets fixed when --lore-version
	// was given.
	pin    syncActionPin
	dryRun bool
	force  bool
	// own is the running lore's version: the default pin when it is a
	// published release.
	own string
}

// ActionResult is what install-action reports.
type ActionResult struct {
	// Path is the workflow file.
	Path string `json:"path"`
	// Status is one of the syncAction* status constants.
	Status syncActionStatus `json:"status"`
	// LoreVersion is the lore release the workflow downloads.
	LoreVersion string `json:"lore_version,omitempty"`
	// Pin says whether lore keeps LoreVersion current (auto) or not (fixed).
	Pin syncActionPin `json:"pin,omitempty"`
	// Branches are the branches whose pushes trigger it (none when manual).
	Branches []string `json:"branches,omitempty"`
	// Manual is true when the workflow only runs by hand (no automatic
	// triggers); Auto is its opposite, spelled out for readers of the JSON.
	Manual bool `json:"manual"`
	Auto   bool `json:"auto"`
	// Content is the generated file (--dry-run only).
	Content string `json:"content,omitempty"`
}

// syncActionStatus is what install-action did (the
// "status" field of their --json output).
type syncActionStatus string

// install-action statuses.
const (
	syncActionCreated   syncActionStatus = "created"
	syncActionUpdated   syncActionStatus = "updated"
	syncActionUnchanged syncActionStatus = "unchanged"
	syncActionDryRun    syncActionStatus = "dry-run"
)

// syncActionStatuses is every status (tests check each is printed).
var syncActionStatuses = []syncActionStatus{syncActionCreated, syncActionUpdated, syncActionUnchanged, syncActionDryRun}

// installSyncAction renders and writes the workflow for the project at dir.
func installSyncAction(ctx context.Context, dir string, o syncActionOptions) (ActionResult, error) {
	top, err := toplevel(ctx, dir)
	if err != nil {
		return ActionResult{}, errs.Wrap(errs.Unsupported, "install-action needs a git repository", err)
	}
	prefix := PathPrefix(top, dir)
	file := filepath.Join(top, filepath.FromSlash(syncActionFileRel(prefix)))
	if o, err = resolveSyncActionTriggers(top, prefix, file, o); err != nil {
		return ActionResult{}, err
	}
	params, err := syncActionParamsFor(ctx, top, dir, o)
	if err != nil {
		return ActionResult{}, err
	}
	content, err := renderSyncAction(params)
	if err != nil {
		return ActionResult{}, errs.Wrap(errs.Internal, "render workflow", err)
	}
	res := ActionResult{Path: file, LoreVersion: params.LoreVersion, Pin: syncActionPinAuto, Manual: o.manual, Auto: !o.manual}
	if o.pin != "" {
		res.Pin = o.pin
	}
	if !o.manual {
		res.Branches = branchesOrDefault(ctx, dir, o.branches)
	}
	if o.dryRun {
		res.Status, res.Content = syncActionDryRun, content
		return res, nil
	}
	existing, err := os.ReadFile(filepath.Clean(file))
	switch {
	case errors.Is(err, fs.ErrNotExist):
		res.Status = syncActionCreated
	case err != nil:
		return res, errs.Wrap(errs.Internal, "read "+file, err)
	case string(existing) == content:
		res.Status = syncActionUnchanged
		return res, nil
	case !strings.HasPrefix(string(existing), syncActionMarker) && !o.force:
		return res, errs.New(errs.AlreadyInitialized, file+" exists and was not generated by lore").
			WithHint("move it away, or pass --force to overwrite it")
	default:
		res.Status = syncActionUpdated
	}
	if err := writeSyncActionFile(file, content); err != nil {
		return res, errs.Wrap(errs.Internal, "write "+file, err)
	}
	if err := removeLegacySyncAction(top, prefix); err != nil {
		return res, errs.Wrap(errs.Internal, "remove the old shared workflow file", err)
	}
	return res, nil
}

// resolveSyncActionTriggers settles o.manual (the triggers to write) and, on
// a re-run without --branch, the branches:
//   - --auto and --manual together are refused;
//   - --auto adds the automatic triggers, --manual removes them;
//   - with neither, an installed lore-generated workflow keeps the triggers
//     it has (an automatic workflow must not silently stop, a manual one
//     must not silently start spending minutes);
//   - a new install (or an unreadable / foreign file) is manual only;
//   - without --branch, an installed workflow keeps its branches.
//
// file is the project's workflow path; the subfolder project's legacy
// root-named file counts as installed when its own file is absent.
func resolveSyncActionTriggers(toplevel, prefix, file string, o syncActionOptions) (syncActionOptions, error) {
	if o.auto && o.manualSet {
		return o, errs.New(errs.InvalidInput, fmt.Sprintf("--%s and --%s contradict each other; pass one", flagAuto, flagManual))
	}
	installed, ok := installedSyncActionSettings(toplevel, prefix, file)
	switch {
	case o.auto:
		o.manual = false
	case o.manualSet:
		o.manual = true
	case ok:
		o.manual = installed.manual
	default:
		o.manual = true // new installs never spend Actions minutes on their own
	}
	if ok && len(o.branches) == 0 {
		o.branches = installed.branches
	}
	return o, nil
}

// installedSyncActionSettings reads the settings of the lore-generated
// workflow at file (or the project's legacy root-named one). ok is false
// when there is none, it is someone else's file, or it cannot be parsed;
// a read error that matters surfaces later, when install-action writes.
func installedSyncActionSettings(toplevel, prefix, file string) (syncActionSettings, bool) {
	b, err := os.ReadFile(filepath.Clean(file))
	if errors.Is(err, fs.ErrNotExist) {
		if legacy := legacySyncActionFor(toplevel, prefix); legacy != "" {
			b, err = os.ReadFile(filepath.Clean(legacy))
		}
	}
	if err != nil || !strings.HasPrefix(string(b), syncActionMarker) {
		return syncActionSettings{}, false
	}
	s, err := parseSyncAction(string(b))
	if err != nil {
		return syncActionSettings{}, false
	}
	return s, true
}

// writeSyncActionFile writes content atomically (temp file + rename), so two
// lore processes refreshing at once never leave a half-written workflow.
func writeSyncActionFile(file, content string) error {
	if err := os.MkdirAll(filepath.Dir(file), syncDirMode); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(file), "."+filepath.Base(file)+".tmp-*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	if _, err := tmp.WriteString(content); err != nil {
		_ = tmp.Close()
		_ = os.Remove(name) // the write error is the one to report
		return err
	}
	if err := tmp.Close(); err != nil {
		_ = os.Remove(name)
		return err
	}
	if err := os.Chmod(name, syncFileMode); err != nil {
		_ = os.Remove(name)
		return err
	}
	return os.Rename(name, file)
}

// legacySyncActionFor returns the shared root-named workflow (the only name
// lore v0.1.11 wrote) when it belongs to the subfolder project at prefix, so
// installing or refreshing that project moves it to the project's own name.
// "" when there is none, or it belongs to another project.
func legacySyncActionFor(toplevel, prefix string) string {
	if prefix == "" {
		return "" // the root project's name never changed
	}
	file := filepath.Join(toplevel, filepath.FromSlash(syncActionFileRel("")))
	b, err := os.ReadFile(filepath.Clean(file))
	if err != nil || !strings.HasPrefix(string(b), syncActionMarker) {
		return ""
	}
	s, err := parseSyncAction(string(b))
	if err != nil || s.workDir != strings.TrimSuffix(prefix, "/") {
		return ""
	}
	return file
}

// removeLegacySyncAction deletes the subfolder project's old root-named file
// after its own file was written.
func removeLegacySyncAction(toplevel, prefix string) error {
	if legacy := legacySyncActionFor(toplevel, prefix); legacy != "" {
		return os.Remove(legacy)
	}
	return nil
}

// syncActionParamsFor validates options and derives the template inputs.
func syncActionParamsFor(ctx context.Context, toplevel, dir string, o syncActionOptions) (syncActionParams, error) {
	ver, err := workflowLoreVersion(o.loreVersion, o.own)
	if err != nil {
		return syncActionParams{}, err
	}
	branches := branchesOrDefault(ctx, dir, o.branches)
	for _, b := range branches {
		if !branchNamePattern.MatchString(b) {
			return syncActionParams{}, errs.New(errs.InvalidInput, fmt.Sprintf("branch name %q has characters install-action does not write into a workflow", b))
		}
	}
	branchesYAML, err := json.Marshal(branches) // a JSON array is a valid YAML flow sequence
	if err != nil {
		return syncActionParams{}, errs.Wrap(errs.Internal, "encode branches", err)
	}
	prefix := PathPrefix(toplevel, dir)
	workDir := strings.TrimSuffix(prefix, "/")
	nameSuffix := ""
	if workDir == "" {
		workDir = rootRel
	} else {
		nameSuffix = " (" + workDir + ")"
	}
	pin := o.pin
	if pin == "" {
		pin = syncActionPinAuto
	}
	return syncActionParams{
		Marker:            syncActionMarker,
		PinLine:           syncActionPinPrefix + string(pin),
		NameSuffix:        nameSuffix,
		Slug:              syncActionSlug(prefix),
		LoreVersion:       ver,
		ReleaseURL:        releaseAssetURL(ver),
		Manual:            o.manual,
		DataGlob:          prefix + dataRel + "/**",
		BranchesYAML:      string(branchesYAML),
		DefaultBranch:     branches[0],
		WorkDir:           workDir,
		CIMergeCommand:    CIMergeCommand,
		OutcomeMerged:     Merged,
		OutcomeNeedsHuman: NeedsHuman,
	}, nil
}

// branchesOrDefault returns the requested branches, or the remote's default
// branch (fallbackDefaultBranch when the clone never recorded one).
func branchesOrDefault(ctx context.Context, dir string, requested []string) []string {
	if len(requested) > 0 {
		return requested
	}
	if b, ok := defaultBranch(ctx, dir, syncActionRemote); ok {
		return []string{b}
	}
	return []string{fallbackDefaultBranch}
}

// workflowLoreVersion picks the release the workflow downloads: the flag when
// given, else this binary's own version when it is a published release, else
// the latest release (a development build has no release to pin to).
func workflowLoreVersion(flag, own string) (string, error) {
	pick := func(v string) string { return "v" + strings.TrimPrefix(v, "v") }
	switch {
	case flag == loreVersionLatest:
		return loreVersionLatest, nil
	case flag != "":
		if !releaseVersionPattern.MatchString(flag) {
			return "", errs.New(errs.InvalidInput, fmt.Sprintf("--%s %q: want vX.Y.Z or %s", flagLoreVersion, flag, loreVersionLatest))
		}
		return pick(flag), nil
	case releaseVersionPattern.MatchString(own):
		return pick(own), nil
	default:
		return loreVersionLatest, nil
	}
}

// releaseAssetURL is the base URL of a release's downloadable assets.
func releaseAssetURL(ver string) string {
	base := "https://github.com/" + loreReleaseRepo + "/releases"
	if ver == loreVersionLatest {
		return base + "/latest/download"
	}
	return base + "/download/" + ver
}

// renderSyncAction fills the template and stamps the checksum line. It uses
// [[ ]] delimiters because the workflow itself is full of GitHub's ${{ }}
// expressions.
func renderSyncAction(p syncActionParams) (string, error) {
	tmpl, err := template.New("workflow").Delims("[[", "]]").Option("missingkey=error").Parse(syncActionTemplate)
	if err != nil {
		return "", err
	}
	p.SumLine = syncActionSumPrefix + syncActionSumPending
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, p); err != nil {
		return "", err
	}
	out := buf.String()
	return strings.Replace(out, p.SumLine, syncActionSumPrefix+syncActionChecksum(out), 1), nil
}

// syncActionChecksum hashes a workflow file without its checksum line, with
// line endings normalised to LF.
func syncActionChecksum(content string) string {
	var kept []string
	for _, l := range strings.Split(strings.ReplaceAll(content, "\r\n", "\n"), "\n") {
		if !strings.HasPrefix(l, syncActionSumPrefix) {
			kept = append(kept, l)
		}
	}
	sum := sha256.Sum256([]byte(strings.Join(kept, "\n")))
	return hex.EncodeToString(sum[:])
}

// syncActionSettings is what an installed workflow file says about itself:
// enough to render it again with another lore version.
type syncActionSettings struct {
	// version is the pinned release ("v0.1.11") or loreVersionLatest.
	version string
	// pin is auto or fixed (files written by v0.1.11 have no pin line and
	// were all installed with the default, so they read as auto).
	pin syncActionPin
	// manual: only workflow_dispatch triggers.
	manual bool
	// branches are the push branches, or [dispatch default] when manual.
	branches []string
	// workDir is the project folder the merge step runs in ("." = root).
	workDir string
	// sum is the recorded checksum ("" for files without one).
	sum string
}

// syncActionFileYAML is the slice of the workflow parseSyncAction reads.
type syncActionFileYAML struct {
	On struct {
		Push *struct {
			Branches []string `yaml:"branches"`
		} `yaml:"push"`
		Dispatch struct {
			Inputs struct {
				Base struct {
					Default string `yaml:"default"`
				} `yaml:"base"`
			} `yaml:"inputs"`
		} `yaml:"workflow_dispatch"`
	} `yaml:"on"`
	Jobs map[string]struct {
		Steps []struct {
			Run              string `yaml:"run"`
			WorkingDirectory string `yaml:"working-directory"`
		} `yaml:"steps"`
	} `yaml:"jobs"`
}

// parseSyncAction reads a generated workflow's settings back from its
// header lines and its YAML.
func parseSyncAction(content string) (syncActionSettings, error) {
	content = strings.ReplaceAll(content, "\r\n", "\n")
	first, _, _ := strings.Cut(content, "\n")
	m := syncActionMarkerVersion.FindStringSubmatch(first)
	if !strings.HasPrefix(first, syncActionMarker) || m == nil {
		return syncActionSettings{}, fmt.Errorf("not a lore-generated workflow (marker line %q)", first)
	}
	s := syncActionSettings{version: m[1], pin: syncActionPinAuto}
	for _, l := range strings.Split(content, "\n") {
		switch {
		case strings.HasPrefix(l, syncActionPinPrefix):
			s.pin = syncActionPin(strings.TrimPrefix(l, syncActionPinPrefix))
		case strings.HasPrefix(l, syncActionSumPrefix):
			s.sum = strings.TrimPrefix(l, syncActionSumPrefix)
		}
	}
	if s.pin != syncActionPinAuto && s.pin != syncActionPinFixed {
		return syncActionSettings{}, fmt.Errorf("unknown pin %q", s.pin)
	}
	var doc syncActionFileYAML
	if err := yaml.Unmarshal([]byte(content), &doc); err != nil {
		return syncActionSettings{}, fmt.Errorf("workflow YAML: %w", err)
	}
	if doc.On.Push == nil {
		s.manual = true
		if d := doc.On.Dispatch.Inputs.Base.Default; d != "" {
			s.branches = []string{d}
		}
	} else {
		s.branches = doc.On.Push.Branches
	}
	if len(s.branches) == 0 {
		return syncActionSettings{}, fmt.Errorf("workflow names no branch")
	}
	for _, job := range doc.Jobs {
		for _, st := range job.Steps {
			if strings.Contains(st.Run, CIMergeCommand) {
				s.workDir = st.WorkingDirectory
			}
		}
	}
	if s.workDir == "" {
		return syncActionSettings{}, fmt.Errorf("workflow has no ci-merge step")
	}
	return s, nil
}

// PinRefresh reports what refreshSyncActionPin did. All fields empty
// means there was nothing to do.
type PinRefresh struct {
	// Path is the workflow file that was rewritten (or would have been).
	Path string `json:"path,omitempty"`
	// From and To are the old and new pinned versions when it was rewritten.
	From string `json:"from,omitempty"`
	To   string `json:"to,omitempty"`
	// Note explains why an out-of-date file was left alone (hand-edited,
	// unreadable).
	Note string `json:"note,omitempty"`
}

// refreshSyncActionPin moves an auto-pinned workflow of the lore project at
// root (inside repo) to own, the running lore's version, when that is a newer
// release. See the file comment for every case it deliberately leaves alone.
// repo is passed in because its caller, the git wiring, has already opened it
// (one git process less on every uncached command).
func refreshSyncActionPin(ctx context.Context, top, root, own string) (PinRefresh, error) {
	target := ""
	if releaseVersionPattern.MatchString(own) {
		target = "v" + strings.TrimPrefix(own, "v")
	}
	if target == "" {
		return PinRefresh{}, nil // a development build has no release to pin to
	}
	prefix := PathPrefix(top, root)
	file := filepath.Join(top, filepath.FromSlash(syncActionFileRel(prefix)))
	b, err := os.ReadFile(filepath.Clean(file))
	if errors.Is(err, fs.ErrNotExist) {
		if legacy := legacySyncActionFor(top, prefix); legacy != "" {
			file = legacy
			b, err = os.ReadFile(filepath.Clean(file))
		}
	}
	if errors.Is(err, fs.ErrNotExist) {
		return PinRefresh{}, nil // not installed: never created here
	}
	if err != nil {
		return PinRefresh{}, err
	}
	content := string(b)
	if !strings.HasPrefix(content, syncActionMarker) {
		return PinRefresh{}, nil // someone else's file
	}
	s, err := parseSyncAction(content)
	if err != nil {
		return PinRefresh{Path: file, Note: "cannot read its settings (" + err.Error() + "); not updating it"}, nil
	}
	if s.pin != syncActionPinAuto {
		return PinRefresh{}, nil
	}
	if s.version != loreVersionLatest && !releaseLess(s.version, target) {
		return PinRefresh{}, nil // same or newer: never downgrade
	}
	// Triggers come from the installed file, never from install-action's
	// default: a version bump must not start or stop a workflow's runs.
	o := syncActionOptions{branches: s.branches, manual: s.manual, pin: syncActionPinAuto}
	if edited, syncErr := syncActionEdited(ctx, top, root, content, s, o); syncErr != nil || edited {
		if syncErr != nil {
			return PinRefresh{}, syncErr
		}
		return PinRefresh{Path: file, Note: "edited by hand, so lore no longer updates it; re-run `lore sync install-action` to take " + target}, nil
	}
	o.loreVersion = target
	params, err := syncActionParamsFor(ctx, top, root, o)
	if err != nil {
		return PinRefresh{}, err
	}
	next, err := renderSyncAction(params)
	if err != nil {
		return PinRefresh{}, err
	}
	dest := filepath.Join(top, filepath.FromSlash(syncActionFileRel(prefix)))
	if err := writeSyncActionFile(dest, next); err != nil {
		return PinRefresh{}, err
	}
	if dest != file {
		if err := os.Remove(file); err != nil {
			return PinRefresh{}, err
		}
	}
	return PinRefresh{Path: dest, From: s.version, To: target}, nil
}

// syncActionEdited reports whether a generated file was changed by hand. A
// file with a checksum line is checked against it. Files from before the
// checksum (lore v0.1.11) are rendered again with their own settings and
// compared line by line, ignoring comments (the header changed since).
func syncActionEdited(ctx context.Context, toplevel, root, content string, s syncActionSettings, o syncActionOptions) (bool, error) {
	if s.sum != "" {
		return syncActionChecksum(content) != s.sum, nil
	}
	o.loreVersion = s.version
	params, err := syncActionParamsFor(ctx, toplevel, root, o)
	if err != nil {
		return false, err
	}
	again, err := renderSyncAction(params)
	if err != nil {
		return false, err
	}
	return yamlLines(again) != yamlLines(content), nil
}

// yamlLines drops comment lines and normalises line endings.
func yamlLines(content string) string {
	var kept []string
	for _, l := range strings.Split(strings.ReplaceAll(content, "\r\n", "\n"), "\n") {
		if !strings.HasPrefix(strings.TrimSpace(l), "#") {
			kept = append(kept, l)
		}
	}
	return strings.Join(kept, "\n")
}

// releaseLess reports whether release tag a ("v0.1.9") is older than b.
// Both must match releaseVersionPattern.
func releaseLess(a, b string) bool {
	pa, pb := releaseParts(a), releaseParts(b)
	for i := range pa {
		if pa[i] != pb[i] {
			return pa[i] < pb[i]
		}
	}
	return false
}

// releaseParts splits "v1.2.3" into its three numbers (zeros on bad input,
// which releaseVersionPattern has already excluded).
func releaseParts(v string) [3]int {
	var out [3]int
	for i, p := range strings.SplitN(strings.TrimPrefix(v, "v"), ".", len(out)) {
		n, err := strconv.Atoi(p)
		if err == nil {
			out[i] = n
		}
	}
	return out
}

// printSyncAction renders an install-action result for a terminal.
func printSyncAction(w *strings.Builder, res ActionResult) {
	switch res.Status {
	case syncActionDryRun:
		w.WriteString(res.Content)
		return
	case syncActionUnchanged:
		fmt.Fprintf(w, "· %s is already up to date\n", res.Path)
		return
	case syncActionCreated, syncActionUpdated:
		// the write lines below
	}
	fmt.Fprintf(w, "%s %s %s\n", "✓", res.Status, res.Path)
	if res.Pin == syncActionPinFixed {
		fmt.Fprintf(w, "  downloads lore %s (pinned: never updated automatically)\n", res.LoreVersion)
	} else {
		fmt.Fprintf(w, "  downloads lore %s; lore moves it to newer releases as developers upgrade (commit those updates)\n", res.LoreVersion)
	}
	if res.Manual {
		fmt.Fprintln(w, "  runs only when started by hand (Actions → lore sync merge → Run workflow)")
		fmt.Fprintf(w, "  re-run with --%s to also run it when lore data changes (spends Actions time)\n", flagAuto)
	} else {
		fmt.Fprintf(w, "  runs when lore data changes on a pull request or on: %s\n", strings.Join(res.Branches, ", "))
	}
	fmt.Fprintln(w, "  commit the file to enable it; add a LORE_SYNC_TOKEN secret if required checks must re-run on its merges")
}

// InstallOptions are `lore sync install-action`'s inputs.
type InstallOptions struct {
	// Dir is the lore project folder (inside the git work tree).
	Dir string
	// Branches whose pushes trigger the job (default: the remote's
	// default branch, else main).
	Branches []string
	// Auto adds the pull_request and push triggers; Manual removes them;
	// neither keeps an installed file's triggers (a new one is manual).
	Auto, Manual bool
	// LoreVersion pins the release the workflow downloads (vX.Y.Z or
	// latest; a pin lore never moves). Empty: Own when it is a release.
	LoreVersion string
	// DryRun returns the file without writing it; Force overwrites a file
	// at that path lore did not generate.
	DryRun, Force bool
	// Own is the running lore's version.
	Own string
}

// Install writes (or, with DryRun, renders) the project's workflow.
func Install(ctx context.Context, in InstallOptions) (ActionResult, error) {
	o := syncActionOptions{branches: in.Branches, auto: in.Auto, manualSet: in.Manual, loreVersion: in.LoreVersion, dryRun: in.DryRun, force: in.Force, own: in.Own}
	if in.LoreVersion != "" {
		o.pin = syncActionPinFixed // --lore-version pins a version lore never changes
	}
	return installSyncAction(ctx, in.Dir, o)
}

// RefreshPin moves the auto-pinned workflow of the lore project at root to
// own when own is a newer release (refreshSyncActionPin; run by a binary's
// per-command git wiring). Nothing to do is a zero PinRefresh.
func RefreshPin(ctx context.Context, root, own string) (PinRefresh, error) {
	top, err := toplevel(ctx, root)
	if err != nil {
		return PinRefresh{}, nil // not a git checkout: no workflow to refresh
	}
	return refreshSyncActionPin(ctx, top, root, own)
}

// ActionLines renders an install-action result for a terminal (a dry run
// prints the file as is).
func ActionLines(res ActionResult) []string {
	var b strings.Builder
	printSyncAction(&b, res)
	s := strings.TrimSuffix(b.String(), "\n")
	if s == "" {
		return nil
	}
	return strings.Split(s, "\n")
}
