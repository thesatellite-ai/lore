// TestDoctorMovedOutLineStagesTidiedLoreMD (devco D-719): `lore store adopt
// --move` without --commit removes the rows' files and the stale
// lore-generated .lore/LORE.md; doctor's note then printed `git add -A
// .lore/data` only, so a person who committed from doctor's line left the
// LORE.md removal unstaged and the file tracked. Now the line names every
// tidied file that is gone and tracked (the same command adopt prints), and
// run exactly as printed it leaves nothing of the move uncommitted. A
// removal already staged is not named (git add of it would fail).
func TestDoctorMovedOutLineStagesTidiedLoreMD(t *testing.T) {
	f := newLiveFixture(t)
	f.s.release()
	top := f.s.top
	const rule = ".lore/data/rules/rul_01a1dd52216a707387008bfd35ae45ba.json"
	const loreMD = ".lore/LORE.md"
	write := func(rel, body string) {
		t.Helper()
		full := filepath.Join(top, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write(rule, `{"_v":2,"_table":"rules","id":"rul_01a1dd52216a707387008bfd35ae45ba","severity":"must","summary":"tests green before push","body":"Run the full test suite before every push"}`+"\n")
	write(loreMD, "<!-- This file is generated by lore render. Do not edit by hand. -->\n\n# web\n")
	gitT(t, top, "add", "-A", "-f", ".lore")
	gitT(t, top, "commit", "-q", "--no-verify", "-m", "rows")
	t.Chdir(top)
	ctx := context.Background()

	// what adopt --move (no --commit) leaves: both files gone, the row recorded
	for _, rel := range []string{rule, loreMD} {
		if err := os.Remove(filepath.Join(top, filepath.FromSlash(rel))); err != nil {
			t.Fatal(err)
		}
	}
	if err := wire.RecordMovedOut(ctx, top, "acme/client_a", []string{rule}); err != nil {
		t.Fatal(err)
	}
	line := movedOutNote(t, f)
	if !strings.Contains(line, loreMD) {
		t.Fatalf("doctor's commit line does not name the removed %s:\n%s", loreMD, line)
	}
	_, cmd, ok := strings.Cut(line, "commit the removal: ")
	if !ok {
		t.Fatalf("doctor's note prints no commit command:\n%s", line)
	}
	assertPrintedGitStepsRun(t, top, cmd, func() {
		if err := f.s.h.preCommit(ctx); err != nil {
			t.Fatalf("the pre-commit refused doctor's own commit: %v", err)
		}
	})
	if out := gitOutT(t, top, "ls-files", ".lore"); out != "" {
		t.Fatalf("after doctor's printed commit the repo still tracks:\n%s", out)
	}
	if out := gitOutT(t, top, "status", "--porcelain", "--", ".lore"); out != "" {
		t.Fatalf("doctor's printed commit left changes uncommitted:\n%s", out)
	}

	// a LORE.md removal already staged is not named: `git add` of it fails
	write(rule, `{"_v":2,"_table":"rules","id":"rul_01a1dd52216a707387008bfd35ae45ba","severity":"must","summary":"tests green before push","body":"Run the full test suite before every push"}`+"\n")
	write(loreMD, "<!-- This file is generated by lore render. Do not edit by hand. -->\n\n# web\n")
	gitT(t, top, "add", "-A", "-f", ".lore")
	gitT(t, top, "commit", "-q", "--no-verify", "-m", "back")
	gitT(t, top, "rm", "-q", loreMD)
	if err := os.Remove(filepath.Join(top, filepath.FromSlash(rule))); err != nil {
		t.Fatal(err)
	}
	if err := wire.RecordMovedOut(ctx, top, "acme/client_a", []string{rule}); err != nil {
		t.Fatal(err)
	}
	line = movedOutNote(t, f)
	if strings.Contains(line, loreMD) {
		t.Fatalf("doctor names a removal already staged (git add of it fails):\n%s", line)
	}
	_, cmd, _ = strings.Cut(line, "commit the removal: ")
	assertPrintedGitStepsRun(t, top, cmd, func() {
		if err := f.s.h.preCommit(ctx); err != nil {
			t.Fatalf("the pre-commit refused doctor's own commit: %v", err)
		}
	})
	if out := gitOutT(t, top, "ls-files", ".lore"); out != "" {
		t.Fatalf("after doctor's printed commit the repo still tracks:\n%s", out)
	}
}

// movedOutNote is doctor's note about rows adopt moved out.
func movedOutNote(t *testing.T, f ltFixture) string {
	t.Helper()
	base, err := liveDoctor{h: f.s.h}.Base(f.ctx, false)
	if err != nil {
		t.Fatal(err)
	}
	for _, n := range base.Notes {
		if strings.Contains(n, "commit the removal: ") {
			return n
		}
	}
	t.Fatalf("doctor has no note about the moved rows: %q", base.Notes)
	return ""
}

// assertPrintedGitStepsRun is the printed-next-step guard for a printed
// git command line ("git -C <dir> add … && git -C <dir> commit -m \"…\""):
// each step runs exactly as printed, from anywhere (hooks off: the
// in-process hook runs as hook before the commit; a test identity), and
// must succeed.
func assertPrintedGitStepsRun(t *testing.T, top, line string, hook func()) {
	t.Helper()
	for _, step := range strings.Split(strings.TrimSpace(line), " && ") {
		args := printedArgs(t, step)
		if len(args) < 4 || args[0] != "git" || args[1] != "-C" || args[2] != top {
			t.Fatalf("printed step is not a git command run from the repo (%s): %q", top, step)
		}
		if args[3] == "commit" {
			hook()
			args = append([]string{"git", "-c", "core.hooksPath=/dev/null", "-c", "user.name=Ada", "-c", "user.email=ada@example.test"}, args[1:]...)
		}
		cmd := exec.Command(args[0], args[1:]...) //nolint:gosec // the test runs the line lore printed
		cmd.Dir = t.TempDir()
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("printed step fails where printed: %s\n%v\n%s", step, err, out)
		}
	}
}

// printedArgs splits a printed shell step on spaces, keeping a "…" span
// as one argument.
func printedArgs(t *testing.T, step string) []string {
	t.Helper()
	var out []string
	for step != "" {
		step = strings.TrimLeft(step, " ")
		if strings.HasPrefix(step, `"`) {
			end := strings.Index(step[1:], `"`)
			if end < 0 {
				t.Fatalf("unbalanced quote in printed step: %s", step)
			}
			out = append(out, step[1:end+1])
			step = step[end+2:]
			continue
		}
		word, rest, _ := strings.Cut(step, " ")
		if word != "" {
			out = append(out, word)
		}
		step = rest
	}
	return out
}
