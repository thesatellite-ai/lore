package wire

import (
	"os"
	"path/filepath"
	"slices"
	"testing"
)

// TestAdoptTidy (devco D-719): `lore store adopt --move` removes the
// stale .lore/LORE.md lore generated (a linked repo renders none, and a
// client repo's leak guard refused every commit touching it), and in a
// repo on the lore 0.1.17 format also its place rows and _meta.json once
// every note left, so nothing of the old format stays (read, never
// migrated). A LORE.md the person wrote stays; so do _meta.json and the
// place rows while another file is left in .lore/data.
func TestAdoptTidy(t *testing.T) {
	const (
		row   = ".lore/data/rules/rul_01a1dd52216a707387008bfd35ae45ba.json"
		place = ".lore/data/projects/prj_01a1dd52216a707387008bfd35ae45bb.json"
		meta  = ".lore/data/_meta.json"
		lmd   = ".lore/LORE.md"
		other = ".lore/data/widgets/wdg_1.json"
		gen   = "<!-- This file is generated by lore render. Do not edit by hand. -->\n# app\n"
	)
	write := func(t *testing.T, top string, files map[string]string) {
		t.Helper()
		for rel, body := range files {
			p := filepath.Join(top, filepath.FromSlash(rel))
			if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
				t.Fatal(err)
			}
		}
	}
	cases := []struct {
		name  string
		old   bool
		files map[string]string
		want  []string
	}{
		{"old-format", true, map[string]string{row: "{}", place: "{}", meta: "{}", lmd: gen, ".lore/data/.DS_Store": "x"}, []string{lmd, meta, place}},
		{"current-format", false, map[string]string{row: "{}", place: "{}", meta: "{}", lmd: gen}, []string{lmd}},
		{"hand-written-lore-md", true, map[string]string{row: "{}", place: "{}", meta: "{}", lmd: "# my notes\n"}, []string{meta, place}},
		{"old-format-other-file-left", true, map[string]string{row: "{}", place: "{}", meta: "{}", lmd: gen, other: "{}"}, []string{lmd}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			top := t.TempDir()
			write(t, top, c.files)
			if err := os.Remove(filepath.Join(top, filepath.FromSlash(row))); err != nil {
				t.Fatal(err)
			}
			dry, err := adoptTidy(top, c.old, []string{row}, false)
			if err != nil {
				t.Fatal(err)
			}
			slices.Sort(dry)
			if !slices.Equal(dry, c.want) {
				t.Fatalf("dry run lists %v, want %v", dry, c.want)
			}
			for _, rel := range c.want {
				if _, err := os.Stat(filepath.Join(top, filepath.FromSlash(rel))); err != nil {
					t.Fatalf("the dry run removed %s", rel)
				}
			}
			got, err := adoptTidy(top, c.old, []string{row}, true)
			if err != nil {
				t.Fatal(err)
			}
			slices.Sort(got)
			if !slices.Equal(got, c.want) {
				t.Fatalf("removed %v, want %v", got, c.want)
			}
			for _, rel := range c.want {
				if _, err := os.Stat(filepath.Join(top, filepath.FromSlash(rel))); !os.IsNotExist(err) {
					t.Fatalf("%s is still there", rel)
				}
			}
			if c.name == "old-format" && ProjectFormatOld(top) {
				t.Fatalf("the repo still reads as a 0.1.17 project after the move")
			}
		})
	}
}
