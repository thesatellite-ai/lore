// TestRenderCoreGolden (r2 render_core, later:118; CFG6): the pinned rows
// of a repo with a shareable and an internal store attached, created out of
// id order, render to goldenWant byte for byte.
func TestRenderCoreGolden(t *testing.T) {
	ctx := context.Background()
	repo := t.TempDir()
	cmd := exec.Command("git", "init", "-q")
	cmd.Dir = repo
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git init: %v %s", err, out)
	}
	if err := os.MkdirAll(filepath.Join(repo, ".lore"), 0o750); err != nil {
		t.Fatal(err)
	}
	yaml := "stores:\n  - name: share\n    url: " + internalStoreAt(t, goldenShareID, rowfs.VisibilityShareable) +
		"\n  - name: inner\n    url: " + internalStoreAt(t, goldenInnerID, rowfs.VisibilityInternal) + "\n"
	if err := os.WriteFile(filepath.Join(repo, filepath.FromSlash(attach.FileName)), []byte(yaml), 0o600); err != nil {
		t.Fatal(err)
	}
	a, err := wire.New(wire.Options{RepoDir: repo, Home: t.TempDir(), FlagActor: "human:alice@example.com",
		RepoIsClient: func(context.Context) (bool, error) { return false, nil }})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = a.Close() })

	project := map[store.Source]string{}
	for i, src := range []store.Source{store.SourceRepo, "share", "inner"} {
		w, cerr := a.CreateWithID(ctx, src, schema.TableProjects, goldenID(t, ids.PrefixProject, "0"+string("123"[i])), map[string]value.Value{"name": text(t, "p-"+string(src))})
		if cerr != nil {
			t.Fatal(cerr)
		}
		project[src] = w.Row.ID.String()
	}
	other, err := a.CreateWithID(ctx, store.SourceRepo, schema.TableProjects, goldenID(t, ids.PrefixProject, "09"), map[string]value.Value{"name": text(t, "other")})
	if err != nil {
		t.Fatal(err)
	}
	archived, err := value.DateTimeOf("2026-01-02T03:04:05Z")
	if err != nil {
		t.Fatal(err)
	}
	trust, err := value.NumberOf("0.9")
	if err != nil {
		t.Fatal(err)
	}
	type mk struct {
		src     store.Source
		table   row.Table
		n       string
		fields  map[string]value.Value
		deleted bool
	}
	rule := func(src store.Source, n, body, sev string, extra map[string]value.Value) mk {
		f := map[string]value.Value{"body": text(t, body), "severity": text(t, sev), "activation": text(t, schema.RuleActivationAlways), "source_kind": text(t, "manual")}
		if p := project[src]; p != "" {
			f["project_id"] = text(t, p)
		}
		for k, v := range extra {
			f[k] = v
		}
		return mk{src: src, table: schema.TableRules, n: n, fields: f}
	}
	hotfix := func(src store.Source, n, title, body, sev string, extra map[string]value.Value) mk {
		f := map[string]value.Value{"title": text(t, title), "body": text(t, body), "severity": text(t, sev), "project_id": text(t, project[src]), "source_kind": text(t, "manual")}
		for k, v := range extra {
			f[k] = v
		}
		return mk{src: src, table: schema.TableHotfixes, n: n, fields: f}
	}
	global := rule(store.SourceRepo, "01", "Global must rule", "must", nil)
	delete(global.fields, "project_id")
	deletedRule := rule(store.SourceRepo, "07", "Deleted rule", "must", nil)
	deletedRule.deleted = true
	deletedHotfix := hotfix(store.SourceRepo, "06", "Deleted", "gone", "high", nil)
	deletedHotfix.deleted = true
	rows := []mk{ // scrambled: the output order must come from the ids
		rule("inner", "09", "Internal must rule", "must", nil),
		rule(store.SourceRepo, "03", "Never commit secrets", "must", nil),
		hotfix("share", "07", "Shared trap", "From the shareable store", "high", nil),
		rule("share", "08", "Shared must rule", "must", nil),
		rule(store.SourceRepo, "04", "Prefer small PRs", "should", nil),
		hotfix(store.SourceRepo, "02", "Retry storm", "Cap retries at 3", "high", nil),
		rule(store.SourceRepo, "05", "Archived rule", "must", map[string]value.Value{"archived_at": archived}),
		global,
		rule(store.SourceRepo, "06", "Other project rule", "must", map[string]value.Value{"project_id": text(t, other.Row.ID.String())}),
		rule(store.SourceRepo, "02", "Trusted rule", "must", map[string]value.Value{"trust_score": trust}),
		rule(store.SourceRepo, "0a", "Manual rule", "must", map[string]value.Value{"activation": text(t, schema.RuleActivationManual)}),
		rule(store.SourceRepo, "0b", "Superseded rule", "must", map[string]value.Value{"superseded_by_id": text(t, goldenID(t, ids.PrefixRule, "03").String())}),
		deletedRule,
		hotfix(store.SourceRepo, "03", "Slow test", "Skip on CI", "medium", nil),
		hotfix(store.SourceRepo, "04", "Archived hotfix", "old", "high", map[string]value.Value{"archived_at": archived}),
		hotfix(store.SourceRepo, "05", "Other project", "elsewhere", "high", map[string]value.Value{"project_id": text(t, other.Row.ID.String())}),
		hotfix(store.SourceRepo, "01", "Pool leak", "Close rows after Query", "critical", nil),
		hotfix("inner", "08", "Internal trap", "never in LORE.md", "critical", nil),
		deletedHotfix,
	}
	for _, r := range rows {
		p := ids.PrefixRule
		if r.table == schema.TableHotfixes {
			p = ids.PrefixHotfix
		}
		id := goldenID(t, p, r.n)
		if _, cerr := a.CreateWithID(ctx, r.src, r.table, id, r.fields); cerr != nil {
			t.Fatalf("%s %s: %v", r.table, id, cerr)
		}
		if r.deleted {
			if _, derr := a.Delete(ctx, engine.Ref{Table: r.table, ID: id}); derr != nil {
				t.Fatal(derr)
			}
		}
	}

	h := New(Options{App: a})
	var skips pinSkips
	pr, err := h.loadPinnedRules(ctx, project[store.SourceRepo], &skips)
	if err != nil {
		t.Fatal(err)
	}
	ph, err := h.loadPinnedHotfixes(ctx, project[store.SourceRepo], &skips)
	if err != nil {
		t.Fatal(err)
	}
	if got := buildFullFile(pr, ph); got != goldenWant {
		t.Fatalf("LORE.full.md differs\n--- got\n%s\n--- want\n%s", got, goldenWant)
	}
	if skips.ManualRules != 1 || skips.SupersededRules != 1 {
		t.Fatalf("skips %+v, want 1 manual + 1 superseded rule", skips)
	}
}

// TestPinnedBlocksMatchV0117: the rule and hotfix blocks are byte-identical
// to a real v0.1.17 render (testdata/v0117_pinned_blocks.txt, cut from
// .lore/LORE.md written by lore 0.1.17 on 2026-11-05); every block is
// re-made from its parsed id, severity, trust, title and body.
func TestPinnedBlocksMatchV0117(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join("testdata", "v0117_pinned_blocks.txt"))
	if err != nil {
		t.Fatal(err)
	}
	var got strings.Builder
	sc := bufio.NewScanner(strings.NewReader(string(raw)))
	var lines []string
	attr := func(open, name string) string {
		_, rest, _ := strings.Cut(open, name+`="`)
		v, _, _ := strings.Cut(rest, `"`)
		return v
	}
	n := 0
	for sc.Scan() {
		l := sc.Text()
		lines = append(lines, l)
		switch l {
		case "</rule>":
			open := lines[0]
			var tr float64
			switch attr(open, "trust") {
			case "0.50":
				tr = 0.5
			default:
				t.Fatalf("fixture trust %q", attr(open, "trust"))
			}
			got.WriteString(ruleFull(pinnedRule{ID: attr(open, "id"), Severity: attr(open, "severity"), TrustScore: tr, Body: strings.Join(lines[1:len(lines)-1], "\n")}))
			lines, n = nil, n+1
		case "</hotfix>":
			open := lines[0]
			title := strings.TrimSuffix(strings.TrimPrefix(lines[1], "**"), "**")
			got.WriteString(hotfixFull(pinnedHotfix{ID: attr(open, "id"), Severity: attr(open, "severity"), Title: title, Body: strings.Join(lines[3:len(lines)-1], "\n")}))
			lines, n = nil, n+1
		case "":
			if len(lines) == 1 {
				lines = nil // the blank line between blocks
			}
		}
	}
	if n != 6 {
		t.Fatalf("fixture has %d blocks, want 6", n)
	}
	if got.String() != string(raw) {
		t.Fatalf("blocks differ from v0.1.17\n--- got\n%s\n--- v0.1.17\n%s", got.String(), raw)
	}
}
