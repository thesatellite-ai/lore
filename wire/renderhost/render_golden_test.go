// goldenID is a fixed id of prefix p ending in the two hex digits n, so
// the expected id order is known up front.
func goldenID(t *testing.T, p ids.Prefix, n string) ids.AnyID {
	t.Helper()
	id, err := ids.ParseAny(string(p) + "_019a00000000700080000000000000" + n)
	if err != nil {
		t.Fatal(err)
	}
	return id
}

