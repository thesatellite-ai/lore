package renderhost

// render_orphan.go — devco:S-1: a LORE.md whose rows are not here.
//
// A repo can carry a .lore/LORE.md that an older lore (or another machine)
// rendered from rows this checkout does not have: no .lore/data rows for
// them and no v0.1.17 lore.db. Rendering there would write an empty file
// over the team's pinned rules and hotfixes, and only git could bring them
// back. Render keeps such a file, says why, and names the two ways on:
// bring the rows in (lore migrate run reads a v0.1.17 lore.db put in
// .lore/), or remove the file to start fresh. lore init says the same.
//
// The test is by id: the file's <rule id=…>/<hotfix id=…>/<memory id=…>
// entries are looked up in this repo's stores, tombstones included (a row
// deleted here is a row this repo knows, so a render that drops it is
// right). One id known, or one id in the new body, and the render goes on.

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/thesatellite-ai/lore/engine"
	"github.com/thesatellite-ai/lore/logic/plural"
	"github.com/thesatellite-ai/lore/logic/toolprofile"
	"github.com/thesatellite-ai/lore/model/ids"
)

// generatedMark is in the header of every LORE.md lore renders, the
// v0.1.17 spelling ("This file is generated by lore render.") and today's
// ("generated by lore render; budget …") alike.
const generatedMark = "generated by lore render"

// entryIDRe finds an entry of a rendered file and its row id:
// `<rule id="rul_…"`, `<hotfix id="hfx_…"`, `<memory id="mem_…"`.
var entryIDRe = regexp.MustCompile(`(?m)^<([a-z]+) id="([a-z]+_[0-9a-f]{8,})"`)

// orphanRender describes a rendered file whose entries have no row here.
type orphanRender struct {
	rel     string         // the file, relative to the repo root (.lore/LORE.md)
	entries int            // entries in the file
	kinds   map[string]int // entries per tag (rule, hotfix, memory)
}

// summary is "2 entries (1 hotfix, 1 rule)".
func (o orphanRender) summary() string {
	names := make([]string, 0, len(o.kinds))
	for k := range o.kinds {
		names = append(names, k)
	}
	slices.Sort(names)
	parts := make([]string, 0, len(names))
	for _, k := range names {
		parts = append(parts, entryCount(o.kinds[k], k))
	}
	return fmt.Sprintf("%s (%s)", plural.Of(o.entries, "entry", "entries"), strings.Join(parts, ", "))
}

// entryCount is "1 memory", "2 memories", "3 rules".
func entryCount(n int, tag string) string {
	if base, ok := strings.CutSuffix(tag, "y"); ok {
		return plural.Of(n, tag, base+"ies")
	}
	return plural.Count(n, tag)
}

// line is what render and init print about it: why the file is kept and
// the exact next steps.
func (o orphanRender) line() string {
	return fmt.Sprintf("%s kept as it is: it was rendered by another lore (an older version or another machine) and its %s have no rows in this repo (no .lore/data row, no lore.db), so a render here would replace it with an empty file. "+
		"To bring the rows in: copy that lore's .lore/lore.db into this repo's .lore/ and run `lore migrate run`, then `lore render`. "+
		"To start fresh instead: `git rm %s` (or delete it), then `lore render`",
		o.rel, o.summary(), o.rel)
}

// findOrphanRender reports the file at path (rel for messages) when it is
// a rendered LORE.md whose entries all lack a row in this repo. newBody is
// what the render would write ("" from init): an id found there is known.
// A host with no app is never asked.
func (h *Host) findOrphanRender(ctx context.Context, path, rel, newBody string) (orphanRender, bool) {
	if h.app == nil {
		return orphanRender{}, false
	}
	b, err := os.ReadFile(filepath.Clean(path))
	if err != nil {
		return orphanRender{}, false
	}
	return orphanOf(string(b), rel, newBody, func(id string) bool {
		anyID, perr := ids.ParseAny(id)
		if perr != nil {
			return false
		}
		_, _, gerr := h.app.Get(ctx, engine.Ref{ID: anyID}) // tombstones count: a row deleted here is known
		return gerr == nil
	})
}

// orphanOf is findOrphanRender's pure part: text is the file on disk and
// known answers whether this repo has a row (live or deleted) for an id.
// A file lore did not render or with no entries is never an orphan; one
// entry whose id is in newBody or known is enough to go on rendering.
func orphanOf(text, rel, newBody string, known func(id string) bool) (orphanRender, bool) {
	if !strings.Contains(text, generatedMark) {
		return orphanRender{}, false
	}
	matches := entryIDRe.FindAllStringSubmatch(text, -1)
	if len(matches) == 0 {
		return orphanRender{}, false
	}
	o := orphanRender{rel: rel, kinds: map[string]int{}}
	seen := map[string]bool{}
	for _, m := range matches {
		tag, id := m[1], m[2]
		if seen[id] {
			continue
		}
		seen[id] = true
		if strings.Contains(newBody, `id="`+id+`"`) || known(id) {
			return orphanRender{}, false
		}
		o.entries++
		o.kinds[tag]++
	}
	return o, true
}

// OrphanRenderLine is lore init's note about the repo's LORE.md (devco
// S-1): the line render will print when it keeps the file, or "" when the
// file is missing or its rows are here.
func (h *Host) OrphanRenderLine(ctx context.Context, root string) string {
	rel := toolprofile.CanonicalOutput
	o, ok := h.findOrphanRender(ctx, filepath.Join(root, filepath.FromSlash(rel)), rel, "")
	if !ok {
		return ""
	}
	return o.line()
}
