package renderhost

import (
	"os"
	"path/filepath"
	"strings"

	"github.com/thesatellite-ai/lore/model/errs"
	"github.com/thesatellite-ai/lore/wire"
)

// The generated out file (default .lore/LORE.md), the pointer files, the
// path rule and folder files and the hook settings files are written
// through wire.WriteThroughLink: a symbolic link is followed to the end of
// its chain (R27 #19 keeps the person's link layout; no link of a chain is
// replaced by a regular file), and a link inside the repository that ends
// outside it is refused (E_REFUSED naming the link and its end).

// fullFileMarker opens every LORE.full.md lore writes (buildFullFile): a
// file of that name without it is someone else's and is never replaced.
const fullFileMarker = "<!-- generated by lore render"

// refuseForeignFull refuses (E_BAD_PATH) when path exists and does not
// start with lore's own header. A missing file, or one lore wrote, passes.
func refuseForeignFull(path string) error {
	data, err := os.ReadFile(filepath.Clean(path))
	if err != nil {
		return nil // missing (or unreadable: the write reports it)
	}
	if strings.HasPrefix(string(data), fullFileMarker) {
		return nil
	}
	return errs.New(errs.BadPath, "refusing to overwrite "+path+": it exists and lore did not write it (render writes "+fullFileName+" next to --out)").
		WithHint("give --out a folder without a " + fullFileName + " of your own, or move that file away")
}

// inRepo is wire.InRepo: one rule for every --target a command writes.
func inRepo(root, p string) bool { return wire.InRepo(root, p) }

// refuseOutsideTarget refuses (E_BAD_PATH) a --target file outside the
// repository: render and init stitch a pointer into each target, and the
// targets are the repo's own tool files, never a file elsewhere.
func refuseOutsideTarget(root, target string) error {
	if inRepo(root, target) {
		return nil
	}
	return errs.New(errs.BadPath, "--target "+target+" is outside the repository; the targets are the repo's own tool files").
		WithHint("give a tool profile name (lore render --target claude_code) or a file inside the repository")
}

// refuseRemoteOut refuses (E_BAD_PATH) an out path outside the repository
// for a call that came over the API (op.Remote): on the CLI --out may name
// any file, the person's own choice; a JSON body may not.
func refuseRemoteOut(root, out string) error {
	if inRepo(root, out) {
		return nil
	}
	return errs.New(errs.BadPath, "out "+out+" is outside the repository; over the API render writes only inside it").
		WithHint("leave out empty (.lore/LORE.md) or name a file inside the repository; run `lore render --out` on the CLI for a file elsewhere")
}
