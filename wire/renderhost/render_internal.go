package renderhost

// render_internal.go — the guards of the second render target (F20, C19,
// ADR TEAM-019, guard 2 in §6.2): internal and personal context is rendered
// OUTSIDE the checkout (render_private.go: one file per internal store,
// ~/.lore/render/<repo_id>/<store_id>.md, spec 7.3 / CFG6), and the
// checkout gets only CLAUDE.local.md holding import lines, excluded through
// .git/info/exclude (never the client's .gitignore). A Docker build, a ZIP
// or an rsync of the checkout therefore carries nothing internal.
import (
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/thesatellite-ai/lore/model/errs"
	"github.com/thesatellite-ai/lore/wire"
)

// Files of the internal render.
const (
	// claudeLocalFile is the per-checkout import file the coding agent reads and
	// git ignores by convention; lore also excludes it explicitly.
	claudeLocalFile = "CLAUDE.local.md"
	// renderHeader is the fixed first line of every internal render
	// (F20): agents must never copy this content anywhere a client reads.
	renderHeader = "<!-- generated by lore; internal: never quote this content in client files, commits, PRs or chat -->"
	// renderFileMode: internal content, readable by the user only.
	renderFileMode = 0o600
	renderDirMode  = 0o700
	// excludeFileMode is git's usual mode for info/exclude.
	excludeFileMode = 0o644
)

// errRenderTarget is a refusal about a private import file (symlink, tracked).
var errRenderTarget = errors.New("refusing to write a private import file")

// checkLocalFile refuses a private import file (rel, a slash path relative
// to root: CLAUDE.local.md or another profile's private file) that is a
// symlink (writing would go wherever it points, maybe a tracked file) or
// that git tracks (its content would be committed).
func checkLocalFile(ctx context.Context, root, rel string) error {
	path := filepath.Join(root, filepath.FromSlash(rel))
	if end, isLink, err := wire.LinkEnd(path); err != nil {
		return err
	} else if isLink {
		return errs.New(errs.LeakBlocked, fmt.Sprintf("%v %s: it is a symlink to %s (the import lines would be written wherever it points)", errRenderTarget, rel, end)).WithHint("delete the symlink; lore writes a plain " + rel)
	}
	if tracked, err := gitTracks(ctx, root, rel); err != nil {
		return errs.Wrap(errs.Internal, "ask git about "+rel, err)
	} else if tracked {
		return errs.New(errs.LeakBlocked, fmt.Sprintf("%v %s: git tracks it, so its content would be committed", errRenderTarget, rel)).WithHint("`git rm --cached " + rel + "` and commit, then render again")
	}
	return nil
}

// gitTracks reports whether path (relative to root) is in git's index. A
// directory that is not a git checkout tracks nothing.
func gitTracks(ctx context.Context, root, path string) (bool, error) {
	out, err := runGit(ctx, true, "-C", root, "ls-files", "--error-unmatch", "--", path)
	if err == nil {
		return true, nil
	}
	var ee *exec.ExitError
	if errors.As(err, &ee) {
		// 1 = not tracked; 128 = not a repo. Both mean "not tracked".
		return false, nil
	}
	return false, fmt.Errorf("git ls-files: %w: %s", err, out)
}

// excludeInGit adds an anchored pattern for root/name to the repo's
// info/exclude (works in linked worktrees: git --git-path resolves it).
// Outside a git checkout it does nothing.
func excludeInGit(ctx context.Context, root, name string) error {
	top, err := gitOutput(ctx, root, "rev-parse", "--show-toplevel")
	if err != nil {
		return nil // not a git checkout: nothing can commit the file
	}
	excl, err := gitOutput(ctx, root, "rev-parse", "--git-path", "info/exclude")
	if err != nil {
		return errs.Wrap(errs.Internal, "locate info/exclude", err)
	}
	if !filepath.IsAbs(excl) {
		excl = filepath.Join(root, excl)
	}
	rel, err := filepath.Rel(top, filepath.Join(root, name))
	if err != nil {
		return errs.Wrap(errs.Internal, "locate "+name, err)
	}
	pattern := "/" + filepath.ToSlash(rel)
	cur, err := os.ReadFile(filepath.Clean(excl))
	if err != nil && !os.IsNotExist(err) {
		return errs.Wrap(errs.Internal, "read info/exclude", err)
	}
	for _, line := range strings.Split(string(cur), "\n") {
		if strings.TrimSpace(line) == pattern {
			return nil
		}
	}
	add := ""
	if len(cur) > 0 && !strings.HasSuffix(string(cur), "\n") {
		add = "\n"
	}
	add += "# lore: internal context import (never commit)\n" + pattern + "\n"
	if mkdirErr := os.MkdirAll(filepath.Dir(excl), renderDirMode); mkdirErr != nil {
		return errs.FileIO("create the git info folder", filepath.Dir(excl), mkdirErr)
	}
	f, err := os.OpenFile(filepath.Clean(excl), os.O_APPEND|os.O_CREATE|os.O_WRONLY, excludeFileMode)
	if err != nil {
		return errs.Wrap(errs.Internal, "open info/exclude", err)
	}
	_, werr := f.WriteString(add)
	if cerr := f.Close(); werr == nil {
		werr = cerr
	}
	if werr != nil {
		return errs.Wrap(errs.Internal, "write info/exclude", werr)
	}
	return nil
}

func gitOutput(ctx context.Context, dir string, args ...string) (string, error) {
	out, err := runGit(ctx, false, append([]string{"-C", dir}, args...)...)
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(out)), nil
}

// oneLine collapses whitespace so a row is one bullet.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
