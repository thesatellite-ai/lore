// render_private.go — the private per-store renders (STORE_SERVER_SPEC
// 7.3, CONFIG_GUIDE CFG6 and the CFG fixups).
//
// Rows of INTERNAL stores (every attached store whose lore-store.yaml does
// not read visibility: shareable: personal `me`, org stores attached by the
// OrgStores hook, topic stores) never reach a committed file. Each one is
// rendered into its own private file outside the checkout:
//
//	~/.lore/render/<repo>-<repo_id>/<store>-<store_id>.md   one per internal store
//	~/.lore/render/<repo>-<repo_id>/index.md                readable map, never imported
//
// and each target tool's uncommitted private file (toolprofile
// Profile.PrivateFile: CLAUDE.local.md for claude_code, a Cursor rule file
// for cursor, a user profile's private_file; FQ13, DECISION P2-CTX-1)
// carries one import per store (`@~/.lore/render/<repo_id>/<store_id>.md`,
// or a "Read …" line for tools without @ imports), hidden through
// .git/info/exclude (never the client's .gitignore). A target without a
// private file gets internal context through `lore context` and the hooks. Committed renders
// (.lore/LORE.md) hold only the repo's rows and shareable stores' rows
// (render_core.go). The same holds in own repos and client repos: nothing
// here is ever written inside the checkout except those private files.
//
// File names start with the repo's or store's name, so a person browsing
// ~/.lore/render sees which is which (B-17), and end with the permanent id,
// which keeps them unique; a renamed repo or store gets a new name and the
// old file (found by its id suffix) is removed.
// The repo id is `repo_id` from .lore/data/_meta.json, which `lore init`
// and `lore sync` stamp (wire.EnsureRepoIdentity, PROV1); a v0.1.17
// checkout not yet synced has none and falls back to its prj_ project id,
// which is just as permanent and local-only. Several
// attached sources of one store (an org store's two folders) share its sto_
// id and therefore one file. A store whose marker carries no id (v0.1.17)
// gets a name-derived file stem so its rows are not dropped.
//
// Budget (CONTEXT_BUDGET 6.1, P3-CTX-2): every private file of one repo
// loads in the same session, so together they share
// context.budget.internal. The pinned rules and hotfixes (each file's
// core) are never cut; the "Other notes" bullets fill what is left, store
// by store in file order, and a file whose bullets did not all fit ends
// with one "N more notes left out" pointer at `lore search`:
//
//	buildPrivateStore ─► privateBody{core, sections}
//	fitPrivate(bodies, budget) ─► texts, shown, left out
//	cores alone over the budget ─► one WARN on stderr (nothing is cut)
//
// Expansion (SECRETS_AND_REFERENCES 12, CONTEXT_BUDGET 6.13):
//
//	row text ─▶ privateExpander ─▶ refpoint Private point
//	              var/res/row: every non-personal target (private team vars too)
//	              personal-store targets: kept (BATCH 16, SQ23); env never; secret as written
//	          ─▶ scanner on the expanded text: a new hit refuses the render (13.2)

