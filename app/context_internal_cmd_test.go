package app

// `lore context --internal` on the release binary (renderhost.CoreExternal
// wired in main): the rows of the attached internal and personal stores,
// never the repo's own, narrowed by --table and --search, and the same
// rows as a --json array.

import (
	"encoding/json"
	"path/filepath"
	"slices"
	"sort"
	"strings"
	"testing"
)

// TestContextInternalCmd: with an internal store "inner" (a memory and a
// decision naming "zebra", a memory that does not) and the personal store
// "me" (one memory naming "zebra") attached, and a repo memory naming
// "zebra", `lore context --internal` prints the four internal and personal
// rows and never the repo's. The matrix crosses --table (none, memories,
// decisions, tasks with no rows) × --search (none, zebra, a word in no
// row); an unknown table is E_INVALID_INPUT naming the tables it reads;
// --json gives the same rows as data[] with table and _source.store.
func TestContextInternalCmd(t *testing.T) {
	t.Parallel()
	w := newCLIWorld(t)
	root := w.initRepo(t)
	// run takes the subtest's t: the subtests below run in parallel.
	run := func(t *testing.T, args ...string) string {
		t.Helper()
		code, out, errOut := w.lore(t, root, args...)
		if code != 0 {
			t.Fatalf("lore %s: exit %d\n%s\n%s", strings.Join(args, " "), code, out, errOut)
		}
		return out
	}
	run(t, "store", "init", "inner", "file://"+filepath.ToSlash(t.TempDir()), "--yes")
	run(t, "store", "init", "me", "--yes")
	run(t, "memory", "add", "--body", "inner zebra memory", "--to", "inner")
	run(t, "memory", "add", "--body", "inner plain memory", "--to", "inner")
	run(t, "decision", "add", "--title", "inner zebra decision", "--body", "chosen for zebra reasons", "--to", "inner")
	run(t, "memory", "add", "--body", "personal zebra memory", "--to", "me")
	run(t, "memory", "add", "--body", "repo zebra memory")

	rows := map[string]struct{ table, store string }{
		"inner zebra memory":    {"memories", "inner"},
		"inner plain memory":    {"memories", "inner"},
		"inner zebra decision":  {"decisions", "inner"},
		"personal zebra memory": {"memories", "me"},
	}
	for _, table := range []string{"", "memories", "decisions", "tasks"} {
		for _, search := range []string{"", "zebra", "nowhereword"} {
			args := []string{"context", "--internal"}
			if table != "" {
				args = append(args, "--table", table)
			}
			if search != "" {
				args = append(args, "--search", search)
			}
			var want []string
			for text, r := range rows {
				if (table == "" || r.table == table) && (search == "" || strings.Contains(text, search)) {
					want = append(want, text)
				}
			}
			sort.Strings(want)
			t.Run(strings.Join(args[2:], " "), func(t *testing.T) {
				t.Parallel()
				out := run(t, args...)
				if !strings.HasPrefix(out, "<!-- generated by lore; internal:") {
					t.Errorf("no internal header:\n%s", out)
				}
				if strings.Contains(out, "repo zebra memory") {
					t.Errorf("the repo's own row is printed:\n%s", out)
				}
				for text := range rows {
					if has, wanted := strings.Contains(out, text), slices.Contains(want, text); has != wanted {
						t.Errorf("%q printed=%v, want %v:\n%s", text, has, wanted, out)
					}
				}
				if empty := strings.Contains(out, "(nothing internal or personal loads in this repo)"); empty != (len(want) == 0) {
					t.Errorf("empty line shown=%v with %d rows:\n%s", empty, len(want), out)
				}

				var env struct {
					Data []struct {
						Table  string `json:"table"`
						Body   string `json:"body"`
						Title  string `json:"title"`
						Source struct {
							Store string `json:"store"`
						} `json:"_source"`
					} `json:"data"`
				}
				js := run(t, append(args, "--json")...)
				if err := json.Unmarshal([]byte(js), &env); err != nil {
					t.Fatalf("--json: %v\n%s", err, js)
				}
				var got []string
				for _, d := range env.Data {
					text := d.Body
					if d.Title != "" {
						text = d.Title
					}
					got = append(got, text)
					if r, ok := rows[text]; !ok || r.table != d.Table || r.store != d.Source.Store {
						t.Errorf("--json row %+v, want one of the internal rows with its table and store", d)
					}
				}
				sort.Strings(got)
				if strings.Join(got, "|") != strings.Join(want, "|") {
					t.Errorf("--json rows %q, want %q", got, want)
				}
			})
		}
	}

	code, _, errOut := w.lore(t, root, "context", "--internal", "--table", "bogus")
	if code == 0 || !strings.Contains(errOut, "E_INVALID_INPUT") || !strings.Contains(errOut, "memories") {
		t.Errorf("--table bogus: exit %d, stderr %q; want E_INVALID_INPUT naming the tables", code, errOut)
	}
}
