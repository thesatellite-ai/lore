package toolprofile

// Path-scoped rule files (CONTEXT_BUDGET 6.7 targets claude_rules and
// cursor_rules, D5): a tool that loads rule files only when the agent
// touches a matching path gets lore's glob rules as such files, so they
// leave the always-loaded core.
//
//	Profile.PathRules ─┬─ zero  → no native path loader (hooks / lore context serve glob rules)
//	                   └─ set   → PathRuleFile(slug) + PathRuleContent(globs, body)
//
// TOOL NEUTRAL: the loader is a profile field like the pointer file, so a
// user profile with its own path-rule mechanism declares it in config.

import (
	"fmt"
	"path"
	"strconv"
	"strings"
)

// PathRuleStyle is how a tool's path-rule file states its globs.
type PathRuleStyle string

// Path-rule styles. Each is the tool's documented frontmatter.
const (
	// PathRulesNone: no native path loader.
	PathRulesNone PathRuleStyle = ""
	// PathRulesPaths is a Markdown file whose YAML frontmatter has a
	// `paths:` list (Claude Code `.claude/rules/*.md`,
	// code.claude.com/docs/en/memory "path-specific rules"). A file
	// without `paths` loads at start, so lore never writes one.
	PathRulesPaths PathRuleStyle = "paths"
	// PathRulesMDCGlobs is a Cursor `.mdc` rule with `globs:` and
	// `alwaysApply: false` (the same shape as lore's folder rule files).
	PathRulesMDCGlobs PathRuleStyle = "mdc_globs"
)

// PathRules is where and how a profile's tool loads path-scoped rules.
type PathRules struct {
	// Dir is the repo-relative slash folder the files go in.
	Dir string `yaml:"dir,omitempty" json:"dir,omitempty"`
	// Style is the frontmatter shape.
	Style PathRuleStyle `yaml:"style,omitempty" json:"style,omitempty"`
}

// PathRulePrefix starts every path-rule file lore writes, so render finds
// and deletes the stale ones (no hidden state).
const PathRulePrefix = "lore-path-"

// HasPathRules reports whether p's tool loads path-scoped rule files.
func (p Profile) HasPathRules() bool {
	return p.PathRules.Style != PathRulesNone && p.PathRules.Dir != ""
}

// PathRuleExt is the file extension of p's path-rule files.
func (p Profile) PathRuleExt() string {
	if p.PathRules.Style == PathRulesMDCGlobs {
		return ".mdc"
	}
	return ".md"
}

// PathRuleFile is the repo-relative file for one glob set, named by slug.
func (p Profile) PathRuleFile(slug string) string {
	return path.Join(p.PathRules.Dir, PathRulePrefix+slug+p.PathRuleExt())
}

// PathRuleContent is the whole generated file for globs holding body.
func (p Profile) PathRuleContent(globs []string, body string) string {
	var b strings.Builder
	b.WriteString("---\n")
	switch p.PathRules.Style {
	case PathRulesPaths:
		b.WriteString("paths:\n")
		for _, g := range globs {
			b.WriteString("  - " + strconv.Quote(g) + "\n")
		}
	case PathRulesMDCGlobs:
		b.WriteString("description: lore rules for " + strings.Join(globs, ", ") + " (generated by lore render)\n")
		b.WriteString("globs: " + strings.Join(globs, ",") + "\nalwaysApply: false\n")
	case PathRulesNone:
	}
	b.WriteString("---\n")
	b.WriteString("<!-- generated by lore render from glob rules; do not edit (lore rule edit <id>) -->\n\n")
	b.WriteString(strings.TrimRight(body, "\n") + "\n")
	return b.String()
}

// validatePathRules checks a user profile's path_rules: a known style and
// a slash folder inside the repo, outside .lore/.
func validatePathRules(p Profile) error {
	pr := p.PathRules
	if pr == (PathRules{}) {
		return nil
	}
	if pr.Style != PathRulesPaths && pr.Style != PathRulesMDCGlobs {
		return fmt.Errorf("tool profile %q: path_rules.style %q is not one of paths, mdc_globs", p.Name, pr.Style)
	}
	clean := path.Clean(pr.Dir)
	if pr.Dir == "" || path.IsAbs(clean) || strings.Contains(pr.Dir, `\`) || clean == ".." || strings.HasPrefix(clean, "../") ||
		clean == ".lore" || strings.HasPrefix(clean, ".lore/") {
		return fmt.Errorf("tool profile %q: path_rules.dir %q must be a slash folder inside the repo, outside .lore/", p.Name, pr.Dir)
	}
	return nil
}
