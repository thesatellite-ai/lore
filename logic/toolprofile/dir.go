package toolprofile

import (
	"path"
	"regexp"
	"strings"
)

// DirKind is how a profile serves a per-directory LORE.md (CONTEXT_BUDGET
// 6.2.4, 6.7). It is derived from the profile's Import and PointerFile, so a
// user profile gets per-folder files by the same rule as a built-in one
// (TOOL NEUTRAL).
type DirKind string

// Per-directory kinds.
const (
	// DirAt: a pointer block `@LORE.md` in <dir>/<pointer file name> (tools
	// that load nested files with imports: claude_code, gemini_cli).
	DirAt DirKind = "at"
	// DirInline: a lore:context block holding the folder's knowledge in
	// <dir>/<pointer file name> (tools without imports that read nested
	// files: AGENTS.md).
	DirInline DirKind = "inline"
	// DirGlobRule: one root rule file per folder with `globs: <dir>/**`
	// next to the profile's rule file (Cursor, CQ11: never nested rule
	// folders).
	DirGlobRule DirKind = "glob_rule"
	// DirNone: the profile has no verified per-folder mechanism; folder
	// knowledge reaches it through `lore context --for-file` and hooks.
	DirNone DirKind = "none"
)

// DirRulePrefix starts every per-folder rule file lore writes, so render can
// find and delete the ones whose folder lost its file (no hidden state).
const DirRulePrefix = "lore-dir-"

// Context block markers of a DirInline file.
const (
	ContextStartMarker = "<!-- lore:context:start -->"
	ContextEndMarker   = "<!-- lore:context:end -->"
)

var contextRe = MarkerRegexp(ContextStartMarker, ContextEndMarker)

// DirTarget is the file p uses for folder dir (a slash path relative to the
// repo root) and its kind; file is "" for DirNone. slug is dir as one
// file-name token (logic/dirscope.Slug).
func (p Profile) DirTarget(dir, slug string) (file string, kind DirKind) {
	if !p.HasPointerFile() {
		return "", DirNone
	}
	nested := !strings.Contains(p.PointerFile, "/")
	switch {
	case p.Import == ImportAt && nested:
		return dir + "/" + p.PointerFile, DirAt
	case p.Import == ImportRead && nested:
		return dir + "/" + p.PointerFile, DirInline
	case p.Import == ImportMDC:
		return path.Join(path.Dir(p.PointerFile), DirRulePrefix+slug+".mdc"), DirGlobRule
	}
	return "", DirNone
}

// DirContent returns the new content of p's folder file for dir given its
// existing content: the pointer block (DirAt), the context block holding
// body (DirInline), or the whole generated rule file (DirGlobRule).
func (p Profile) DirContent(kind DirKind, existing, dir, body string) string {
	switch kind {
	case DirAt:
		return p.StitchPointer(existing, Link{FromPointer: "LORE.md", FromRoot: dir + "/LORE.md"})
	case DirInline:
		block := ContextStartMarker + "\n" + strings.TrimRight(body, "\n") + "\n" + ContextEndMarker + "\n"
		return p.Place(existing, block, contextRe)
	case DirGlobRule:
		return "---\ndescription: lore knowledge for " + dir + "/ (generated by lore render)\nglobs: " + dir + "/**\nalwaysApply: false\n---\n" +
			PointerStartMarker + "\n" +
			"Read `" + dir + "/LORE.md` before changing files under " + dir + "/: it holds this folder's rules and pinned warnings, generated by `lore render`.\n" +
			PointerEndMarker + "\n"
	case DirNone:
	}
	return existing
}

// DirStrip removes lore's blocks (pointer and context) from content; empty
// reports whether nothing but whitespace is left (the file was lore's own
// and can be deleted, 6.2.5).
func DirStrip(content string) (rest string, empty bool) {
	for _, re := range []*regexp.Regexp{pointerRe, contextRe} {
		content = re.ReplaceAllLiteralString(content, "")
	}
	// Place put the block on top followed by one blank line; drop it too.
	content = strings.TrimLeft(content, "\n")
	return content, strings.TrimSpace(content) == ""
}
