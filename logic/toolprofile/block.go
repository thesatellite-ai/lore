package toolprofile

import (
	"regexp"
	"strings"
)

// Pointer block markers. The block between them is lore's and is replaced in
// place on every render; everything outside is the user's.
const (
	PointerStartMarker = "<!-- lore:pointer:start -->"
	PointerEndMarker   = "<!-- lore:pointer:end -->"
)

// pointerRe matches an existing pointer block (across newlines, non-greedy).
var pointerRe = MarkerRegexp(PointerStartMarker, PointerEndMarker)

// MarkerRegexp matches one block bounded by start and end (and the newline
// after it), the shape of every block lore stitches into a user's file.
func MarkerRegexp(start, end string) *regexp.Regexp {
	return regexp.MustCompile(`(?s)` + regexp.QuoteMeta(start) + `.*?` + regexp.QuoteMeta(end) + `\n?`)
}

// HasPointer reports whether content carries lore's pointer block.
func HasPointer(content string) bool { return pointerRe.MatchString(content) }

// mdcFrontmatter opens a Cursor rule file lore creates: alwaysApply puts the
// rule (and so the pointer to LORE.md) in every request.
const mdcFrontmatter = "---\ndescription: lore project knowledge (generated by lore render)\nalwaysApply: true\n---\n"

// frontmatterDelim opens and closes a YAML frontmatter.
const frontmatterDelim = "---\n"

// Link is where LORE.md is, as seen from a pointer file.
type Link struct {
	// FromPointer is LORE.md's path relative to the pointer file's folder:
	// what an `@` import resolves.
	FromPointer string
	// FromRoot is LORE.md's path relative to the repo root: what a sentence
	// addressed to the agent names.
	FromRoot string
}

// PointerBlock is p's pointer block for LORE.md at link. ImportAt keeps
// v0.1.17's exact bytes; the read styles name the file from the repo root
// because the agent, not an import resolver, follows them.
func (p Profile) PointerBlock(link Link) string {
	switch p.Import {
	case ImportAt:
		return PointerStartMarker + "\n" +
			"@" + link.FromPointer + "\n" +
			"<!-- if your agent does not support @import, read " + link.FromPointer + " now -->\n" +
			PointerEndMarker + "\n"
	case ImportRead, ImportMDC:
		return PointerStartMarker + "\n" +
			"Read `" + link.FromRoot + "` (at the repository root) before answering: it holds this project's rules and pinned warnings, generated by `lore render`.\n" +
			PointerEndMarker + "\n"
	case ImportNone:
	}
	return ""
}

// StitchPointer returns content with p's pointer block for link in place.
func (p Profile) StitchPointer(content string, link Link) string {
	return p.Place(content, p.PointerBlock(link), pointerRe)
}

// Place returns content with block placed: an existing block matched by re
// is replaced in place (literally, so a "$" in block is never read as a
// capture reference); otherwise block goes at the top, separated by a blank
// line. For ImportMDC the top is after the frontmatter, which must stay
// first for the tool to read it, and a new file starts with lore's
// frontmatter.
func (p Profile) Place(content, block string, re *regexp.Regexp) string {
	if re.MatchString(content) {
		return re.ReplaceAllLiteralString(content, block)
	}
	if p.Import == ImportMDC {
		if content == "" {
			return mdcFrontmatter + block
		}
		if front, rest, ok := splitFrontmatter(content); ok {
			if rest == "" {
				return front + block
			}
			return front + block + "\n" + rest
		}
	}
	if content == "" {
		return block
	}
	return block + "\n" + content
}

// splitFrontmatter splits a leading YAML frontmatter (delimiters included)
// from the rest of content; ok is false without one.
func splitFrontmatter(content string) (front, rest string, ok bool) {
	if !strings.HasPrefix(content, frontmatterDelim) {
		return "", content, false
	}
	body := content[len(frontmatterDelim):]
	i := strings.Index(body, "\n"+frontmatterDelim)
	if i < 0 {
		return "", content, false
	}
	end := len(frontmatterDelim) + i + 1 + len(frontmatterDelim)
	return content[:end], content[end:], true
}
