package toolprofile

import "testing"

// TestGeneratedBanner pins D-2: a tool file another generator owns is
// recognised by its banner; ordinary files and lore's own lines are not.
func TestGeneratedBanner(t *testing.T) {
	cases := []struct {
		name, content string
		want          bool
	}{
		{"html banner", "# Acme\n\n<!-- GENERATED FILE — do not edit directly. Run make docs to regenerate. -->\nrules\n", true},
		{"go style", "// Code generated by docgen. DO NOT EDIT.\n", true},
		{"at-generated", "<!-- @generated -->\n", true},
		{"plain", "# Acme\n\nWe never edit migrations by hand.\n", false},
		{"lore block only", PointerStartMarker + "\n<!-- do not edit this block -->\n" + PointerEndMarker + "\n# Acme\n", false},
		{"lore's own file", "<!-- generated by lore render from glob rules; do not edit -->\n", false},
		{"banner far below", "# Acme\na\nb\nc\nd\ne\nf\ng\nh\ni\nj\nk\nl\nm\nn\no\n<!-- GENERATED FILE -->\n", false},
	}
	for _, c := range cases {
		if got := GeneratedBanner(c.content) != ""; got != c.want {
			t.Errorf("%s: GeneratedBanner = %v, want %v", c.name, got, c.want)
		}
	}
}
